// apps/server/src/memory/rules.ts
// Правило памяти ПОСЛЕ реформы (§А8, В7): машиночитаемая часть правила лежит в СВОЙСТВАХ
// (`orbis/rule_pattern`, `orbis/rule_target`, `orbis/rule_scope`), а `title` — генерируемая
// подпись, которую никто не разбирает.
//
// ЧТО ИМЕННО ЭТО ЧИНИТ. До реформы правило записывалось строкой «паттерн → категория» в
// заголовке, и разбирали её ЧЕТЫРЕ независимых потребителя (быстрый ввод, резолв импорта,
// гейт эквивалентности эскалации, две подсветки web). Отсюда два класса дефектов сразу:
//  • «записанное, но молча мёртвое правило» — заголовок без разделителя проходил запись и
//    не работал ни в одном детерминированном пути; экран памяти показывал его как рабочее.
//    Класс закрыт ДАННЫМИ: строки каталога `memory_rule_pattern`/`memory_rule_target`
//    (`builtin-rules.ts`, условная обязательность) и граница типа `orbis/rule_pattern` (пустой и
//    пробельный образец) — правило без образца незаписываемо (fail-closed);
//  • «переименование категории отвязывает правило» — правая часть хранилась НАЗВАНИЕМ.
//    Класс закрыт типом свойства: `orbis/rule_target` — ссылка (ref) на запись категории,
//    и переименование её не трогает.
//
// Подпись генерируется ЗДЕСЬ и только здесь: второй сборщик той же строки в web означал бы
// второй формат, а формат подписи после реформы ни на что не влияет — его никто не читает
// обратно. Web показывает правило СТРУКТУРНО (образец + бейдж категории), поэтому копии
// формата у него нет вовсе.
import { type ContractId, normalizeCounterparty } from '@orbis/shared';

/** Аспект-носитель памяти. */
export const MEMORY_ASPECT = 'orbis/memory';
/** Род записи памяти: `fact` | `rule`. */
export const MEMORY_KIND = 'orbis/memory_kind';
/** Образец правила — текст, по которому правило узнаёт ввод. */
export const RULE_PATTERN = 'orbis/rule_pattern';
/** Правая часть правила — ссылка на категорию (ref, переживает переименование). */
export const RULE_TARGET = 'orbis/rule_target';
/** Область правила — ссылка на контракт реестра; отсутствие = глобальное правило. */
export const RULE_SCOPE = 'orbis/rule_scope';

/**
 * Область денежных правил памяти (§А8/В3): `orbis/rule_scope` стал ссылкой на КОНТРАКТ, и
 * прежний `orbis/financial` (id аспекта) сервер с Задачи 11 не принимает. Литерал ОДИН на
 * сервер: оба его читателя (эскалация, резолв импорта) обязаны называть одну и ту же область —
 * разъехавшись, они дали бы правило, которое подавляет предложение, но не применяется. Третий
 * читатель — fail-closed формы — с задачи 14 строка каталога `memory_rule_target` (shared): она
 * держит тот же литерал в `when`, а расхождение ловит корпус близнецов (запись «денежное правило
 * памяти без цели»).
 */
export const CONTRACT_MONEY_MOVEMENT = 'orbis/money-movement' satisfies ContractId;

/** Стрелка подписи — U+2192 RIGHTWARDS ARROW, с пробелами вокруг. */
const LABEL_ARROW = '→';

/**
 * Генерируемая подпись правила → `title` записи.
 *
 * Это ПОДПИСЬ, а не хранилище: обратной функции нет и не будет — её отсутствие и есть
 * суть В7. Поэтому подпись вправе быть неполной (правило без цели показывается одним
 * образцом): потерять ею нечего, вся правда лежит в свойствах.
 *
 * `title` пишется своим полем вызова, а не через `props`: у core-проекции `orbis/title`
 * хранение — колонка, и запись в `props` под тем же именем валидатор отвергает
 * (`CORE_IN_PROPS`, Задача 16).
 */
export function formatRuleLabel(pattern: string, targetTitle: string): string {
  const left = pattern.trim();
  const right = targetTitle.trim();
  return right === '' ? left : `${left} ${LABEL_ARROW} ${right}`;
}

/** Токен из одних (ASCII-)цифр: сумма/номер карты/номер точки — в образец не входит. */
const DIGITS_ONLY = /^\d+$/;

/**
 * Образец из заголовка ТРАНЗАКЦИИ (не правила): normalizeCounterparty(title) минус токены
 * из одних цифр. «ЯНДЕКС.ТАКСИ 450» → «яндекс такси». Пустая строка, если ничего не
 * осталось («450», «SBOL 1234») — такой образец правилом быть не может, вызывающий обязан
 * выйти.
 *
 * Переехала сюда из `@orbis/shared/memory/rule` под честным именем (находка 30): функция
 * всегда была про заголовок транзакции, а не про заголовок правила, и живёт после реформы —
 * эскалация читает ею СЫРОЙ заголовок выписки, где никакого правила ещё нет. Прежнее имя
 * `rulePatternFromTitle` заставляло читать её как парсер правила и держало её в одном файле
 * с парсером, который реформа удаляет.
 *
 * Своей нормализации не заводим: и дедуп импорта (§3.4.1), и резолв правил (D4) обязаны
 * видеть одни и те же байты.
 *
 * Результат — НЕПОДВИЖНАЯ ТОЧКА normalizeCounterparty: нормализация прогоняется повторно
 * после снятия числовых токенов, потому что служебный токен может оказаться первым только
 * после этого снятия — «1234 CARD ПЯТЁРОЧКА» давало «card пятерочка». Цена неканоничности
 * была не косметической: гейт «эквивалентное правило уже есть» сравнивал образец с
 * нормализованным и не находил совпадения (приходило предложение УЖЕ созданного правила).
 */
export function patternFromTransactionTitle(title: string): string {
  const normalized = normalizeCounterparty(title);
  if (normalized === '') return '';
  return normalizeCounterparty(
    normalized
      .split(' ')
      .filter((token) => !DIGITS_ONLY.test(token))
      .join(' '),
  );
}
