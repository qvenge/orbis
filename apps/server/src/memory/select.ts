// apps/server/src/memory/select.ts
// ЕДИНЫЙ отбор записей памяти — один предикат вместо четырёх копий.
//
// Копий было именно четыре (быстрый ввод через web-запрос, резолв импорта, гейт
// эквивалентности эскалации, слой памяти промпта), и расходились они не гипотетически:
// слой промпта до этой задачи читал СТАРУЮ карту (`aspects_legacy ? 'orbis/memory'`), а
// остальные трое — уже `props`/`aspects[]`, то есть отвечали на вопрос по РАЗНЫМ КОЛОНКАМ.
//
// Где эти колонки расходятся — названо точно, потому что «где-нибудь да разойдутся» это не
// довод. Обычная правка через исполнителя их не разводит: `projectLegacyAspects` пишет
// `aspects_legacy` из тех же `props`/`aspects[]`, поэтому даже `detach` аспекта снимает ключ
// в обеих колонках сразу. Разводят ровно два источника: (1) строки, записанные ДО миграции
// 0015 — она переименовала колонку и НИЧЕГО не конвертировала, так что у них полна старая
// карта и пусты `props`/`aspects[]`; такую запись памяти слой промпта видел, а три
// остальных потребителя — нет; (2) прямая запись в БД мимо исполнителя (фикстура
// `divergentEntityRow` заведена ровно под неё).
//
// Предикат объявляется здесь один раз и отдаётся фрагментом SQL, потому что потребители
// ходят в базу по-разному: двое — сырым `tx.execute`, двое — конструктором drizzle.
//
// ИМЕНА КОЛОНОК НЕКВАЛИФИЦИРОВАННЫЕ (`aspects`, `props`, `archived`) намеренно: фрагмент
// обязан подставляться и в сырой `... FROM entities WHERE <тут>`, и в `.where(<тут>)`
// drizzle. Алиас таблицы во фрагменте сделал бы законным ровно один из двух вызовов.
import { type SQL, sql } from 'drizzle-orm';
import { MEMORY_ASPECT, MEMORY_KIND, RULE_SCOPE } from './rules';

/**
 * Активная запись памяти владельца: носитель навешен, запись не в архиве (§7.4 — архивная
 * память в контекст не инжектится).
 *
 * Признак носителя — принадлежность СПИСКУ `aspects[]`, а не `props`: `->>`-фильтры по
 * `props` индексом не покрываются, и каждое чтение памяти сканировало бы все неархивные
 * записи владельца (после CSV-импортов это тысячи строк).
 *
 * ФОРМА ИМЕННО `@>`, А НЕ `= ANY`, И ЭТО ЗАМЕР, А НЕ ВКУС. GIN по `text[]`
 * (`entities_aspects_gin`, 0015) обслуживает `@>`/`<@`/`&&`, но НЕ `элемент = ANY(массив)`:
 * у второй формы нет индексируемого оператора, и планировщик уводит её в фильтр. На 20 000
 * записей владельца (40 из них — память) разница снята EXPLAIN'ом живьём: `= ANY` — Seq
 * Scan, 19 974 строки отброшены фильтром, `Buffers: shared hit=1144`; `@>` — Bitmap Index
 * Scan по `entities_aspects_gin`, `shared hit=221`. Селектор читается на КАЖДОЕ сообщение
 * владельца (слой памяти системного канала), поэтому форма здесь не косметика.
 *
 * Утверждение проверяемо и запиннено: `select.test.ts` смотрит план и требует, чтобы
 * условие по `aspects` стояло `Index Cond` у `entities_aspects_gin`, а не в `Filter`.
 */
export function memoryEntitiesWhere(): SQL {
  return sql`NOT archived AND aspects @> ARRAY[${MEMORY_ASPECT}]::text[]`;
}

/**
 * Активные ПРАВИЛА памяти, применимые к области `scope`.
 *
 * Глобальные правила (без `orbis/rule_scope`) входят в выборку любой области — так
 * описывает пустую область реестр («пусто = глобально») и так же её понимает приоритет
 * §7.4 («scoped раньше глобальных»). До этой задачи оба денежных потребителя требовали
 * области СТРОГО, и глобальное правило, которое владелец видел в «Памяти AI», не работало
 * ни в быстром вводе, ни в импорте — тот же класс «записано и молча мертво», только с
 * другой стороны.
 */
export function memoryRulesWhere(scope: string): SQL {
  return sql`${memoryEntitiesWhere()}
    AND props ->> ${MEMORY_KIND} = 'rule'
    AND (props ->> ${RULE_SCOPE} = ${scope} OR NOT props ? ${RULE_SCOPE})`;
}
