// Числа среза рутин (V1) — в одном месте, потому что их читают и раннер, и реестр тулов,
// и тесты: значение, переписанное руками во второе место, разъезжается молча.

/**
 * Потолок операций в одном предложении (V1.6). Предложение владелец читает целиком и
 * решает по нему «всё или ничего» — список, который не помещается на экран, это не
 * предложение, а требование довериться.
 *
 * Зеркалит `.max(50)` схемы `proposeInput` (@orbis/shared/contracts/agent-loop): та —
 * контракт входа, эта константа — то же число для рукописной JSON Schema реестра
 * (tools/registry.ts). Расхождение ловит тест формы в routines/propose.test.ts
 * (51 операция → VALIDATION).
 */
export const MAX_PROPOSAL_OPERATIONS = 50;

/**
 * Дедлайн прогона (V1.5). Проверяется МЕЖДУ шагами цикла, а не внутри обращения к
 * модели (Р-15): таймаут одного шага у провайдера свой (180 с) и внешнего сигнала он
 * не принимает — значит в худшем случае прогон живёт дедлайн плюс один шаг. Это цена
 * того, что раннер собран из существующих деталей; переписывать транспорт ради минуты
 * точности V1 не станет.
 */
export const RUN_DEADLINE_MS = 10 * 60_000;

/**
 * Сколько прошлых прогонов рутины уезжает модели историей (Р-18). У `claim_task`
 * история без лимита — для ежедневной рутины это линейный рост контекста; семь дней
 * отвечают на «что было на этой неделе», а всё старшее для решения «что делать
 * сегодня» уже не работает.
 */
export const ROUTINE_HISTORY_TAIL = 7;

/**
 * Стоп-кран (V1.12): столько ПЛАНОВЫХ прогонов подряд, закончившихся `failed`, ставят
 * рутину на паузу. Ручные прогоны в счёт не идут — их запускает владелец и сразу видит
 * результат; на паузу его ставит собственный фон, а не собственная кнопка.
 */
export const CONSECUTIVE_FAILURES_TO_PAUSE = 3;
