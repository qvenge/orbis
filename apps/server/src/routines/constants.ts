/**
 * Русский плюрал правок: 1 правка, 2 правки, 5 правок — сводку читает владелец.
 *
 * Лежит здесь по той же причине, что и словарь выше: читателей стало два. Сводку пишет и
 * составление предложения (propose.ts), и лестница правки (lifecycle.ts) — у правленого
 * предложения строка ленты обязана выглядеть так же, как у исходного, а не «2 операции».
 */
export function editsNoun(n: number): string {
  const mod100 = n % 100;
  if (mod100 >= 11 && mod100 <= 14) return 'правок';
  const mod10 = n % 10;
  if (mod10 === 1) return 'правка';
  if (mod10 >= 2 && mod10 <= 4) return 'правки';
  return 'правок';
}

