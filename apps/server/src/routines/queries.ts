// apps/server/src/routines/queries.ts
// Запросы домена рутин (V1). Запрос ниже — единственный в срезе, который идёт под
// служебной ролью, без identity: ему открыт ровно список владельцев (миграция 0013).
// Всё остальное чтение рутин живёт под withIdentity(владелец) и обычной RLS.
import type { Db } from '../db/client';
import { userSettings } from '../db/schema';

/**
 * Список владельцев для тика планировщика — под серверной ролью orbis_app, без identity.
 *
 * Владельца у тика нет: он их только перечисляет, а работу по каждому ведёт уже под
 * `withIdentity(владелец)` (V1.13, инвариант 14). Отсюда источник — user_settings, а не
 * entities: строка настроек заводится онбордингом ровно одна на владельца, и это самый
 * узкий по данным способ узнать «кто вообще есть» — тела рутин служебной роли не
 * открываются (политика 0013 — FOR SELECT только на эту таблицу).
 *
 * Отбор «есть ли у владельца активные рутины» здесь НЕ делается: он идёт уже под
 * identity владельца (`activeRoutines`, Задача 7). Сузить его сюда значило бы читать
 * граф служебной ролью — ровно то, чего инвариант 14 не разрешает.
 *
 * Порядок фиксирован: два сосуществующих деплоя (Render держит старый и новый контейнер
 * между релизами) тикают в одну и ту же минуту, и одинаковый порядок обхода делает их
 * гонку за бакет воспроизводимой, а не «через раз».
 */
export async function ownerIdsForScheduler(db: Db): Promise<string[]> {
  const rows = await db
    .select({ ownerId: userSettings.ownerId })
    .from(userSettings)
    .orderBy(userSettings.ownerId);
  return rows.map((r) => r.ownerId);
}
