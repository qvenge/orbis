// apps/server/src/seed/gardener.ts
// «Садовник словаря» (§А2-7, Р17) — ПЕРВАЯ сущность-рутина в сидах владельца: раз в неделю
// (понедельник, 09:00 по локальному времени) он проходит по словарю свойств, предлагает
// слить дубли и приносит отчёт о сиротах и о залежавшихся предложениях.
//
// ЗАЧЕМ ОН ВООБЩЕ ЕСТЬ. Реформа отдала модели право заводить свои свойства (Р14), а у права
// заводить есть обратная сторона: словарь разрастается, и в нём заводятся два имени одного
// смысла («усилие» и «уровень усилия»), свойства без единого носителя и без единого значения
// и предложения, о которых владелец забыл. Ни одну из трёх болезней нельзя вылечить на
// записи — «это одно и то же?» решается по СМЫСЛУ, а не по форме, — поэтому лечение вынесено
// в фоновую работу, которая приносит владельцу карточки, а не правит словарь молча.
//
// ПОЧЕМУ РЕЖИМ `act`, А НЕ `propose` (рулинг Р-16-1). В режиме `propose` рутине из мутаций
// доступен РОВНО `orbis_propose` (`tools/registry.ts`, `routineToolAllowed`), а `orbis_propose`
// принимает только правки ГРАФА (entity_create/update, relation_create/delete) — операции
// реестра в него не входят. То есть в `propose` садовник не смог бы предложить слияние
// НИКАКИМ вызовом, и отложенная единица §С8-11, построенная Задачей 16 ровно под него,
// осталась бы механизмом без единственного вызывателя.
//
// ПРАВ ЭТО НЕ РАСШИРЯЕТ, и это проверяется тестом, а не обещается докблоком: `property_merge`
// от рутины классифицируется `behavior-delta` (§7.10, `policy/confirmation.ts`), ряд 4a
// поднимает его до `explicit-confirmation`, и фоновый вызов на этом уровне не исполняется, а
// ложится ОТЛОЖЕННОЙ ЕДИНИЦЕЙ в пачку владельца. До `execute` слияние не доходит ни одним
// путём; всё, что садовник может сделать сам, — сложить карточку, которую примет владелец.
// Встроенные строки реестра (`orbis/…`) ему закрыты по ОБЪЕКТУ и не откладываются никогда
// (`system-object` → `routineDeferForbidden`).
//
// БЕЛЫЙ СПИСОК — РОВНО ОДИН ТУЛ. Чтения (`property_catalog` в том числе) открыты рутине в
// любом режиме, а два способа спросить владельца (`orbis_checkpoint`, `orbis_ask`) —
// `ROUTINE_BASE_TOOLS`. Значит списку остаётся ровно то, чем садовник действительно правит
// систему, и это `property_merge`.
//
// СЕВ ИДЁТ ЧЕРЕЗ ИСПОЛНИТЕЛЯ, А НЕ ПРЯМЫМ SQL (рулинг Р-17-1). Остальные 18 сущностей
// онбординга пишутся `tx.insert` мимо конвейера — им это сходит с рук, потому что их поля
// проверяет тест против схемы аспекта. Садовник — рутина, то есть носитель ДОВЕРЕННОСТИ
// (`orbis/routine_mode`, `orbis/allowed_tools`), и посеянный сырым SQL он был бы правами,
// которые не прошли ни одного валидатора. Через `execute` строка проходит стадию 2
// (`validateEntityProps` по эффективному реестру) — ту же, что и любая правка владельца.
import { ORBIS_NAMESPACE } from '@orbis/shared';
import { sql } from 'drizzle-orm';
import { v5 as uuidv5 } from 'uuid';
import type { Db } from '../db/client';
import { withIdentity } from '../db/with-identity';
import { execute } from '../executor/executor';

/**
 * Слаг садовника. Формула id — та же, что у категорий и смарт-листов (`onboarding.ts`):
 * uuidv5 от owner_id и стабильного слага, то есть id воспроизводим без обращения к БД, и
 * идемпотентность сева держится им, а не флагом.
 */
export const GARDENER_SLUG = 'dictionary-gardener';

/** id садовника у этого владельца — детерминированный, как `seedCategoryId`. */
export function seedRoutineId(ownerId: string, slug: string): string {
  return uuidv5(`${ownerId.toLowerCase()}:seed-routine:${slug}`, ORBIS_NAMESPACE);
}

export const GARDENER_TITLE = 'Садовник словаря';

/**
 * Белый список садовника — РОВНО `property_merge` (Р-16-1). Экспортируется, потому что на
 * него смотрит тест доверенности: «ровно один тул» — это утверждение о правах, и переписав
 * его литералом в тесте, мы проверяли бы копию, а не сид.
 */
export const GARDENER_ALLOWED_TOOLS = ['property_merge'] as const;

/**
 * Свойства рутины (§А1-1 — плоско по id свойства, а не картой аспекта).
 *
 * Понедельник 09:00: словарь меняется медленно, и ежедневный проход был бы платой за AI
 * без нового материала. Утро понедельника — момент, когда владелец разбирает пачку за
 * неделю, и карточки садовника попадают в ту же разборку, а не приезжают посреди работы.
 */
export const GARDENER_PROPS: Readonly<Record<string, unknown>> = {
  'orbis/routine_stage': 'active',
  'orbis/routine_at': '09:00',
  'orbis/routine_days': ['mo'],
  'orbis/routine_mode': 'act',
  'orbis/allowed_tools': [...GARDENER_ALLOWED_TOOLS],
};

/**
 * ИНСТРУКЦИЯ САДОВНИКА — тело сущности (V1.1: «что делать» у рутины лежит в теле обычным
 * текстом, в свойствах только расписание и права).
 *
 * Три раздела — по одной болезни словаря на раздел, и порядок в них не случаен: слияние
 * идёт первым, потому что оно единственное, что садовник ДЕЛАЕТ; сироты и залежавшиеся
 * предложения — то, о чём он только рассказывает. Начав с рассказа, модель тратила бы шаги
 * прогона на текст и до работы могла не дойти.
 *
 * ОТЧЁТ — ФИНАЛЬНЫЙ ТЕКСТ ХОДА, а не вызов инструмента, и это не выбор стиля: в белом
 * списке садовника ровно `property_merge` (Р-16-1), `thread_post` ему недоступен, а
 * `orbis_ask` — вопрос с карточкой в пачке, а не отчёт. Системный слой act-режима
 * (`llm/prompts/routine-v3.ts`) говорит про финальный текст то же самое, поэтому инструкция
 * его не переопределяет, а только называет, ЧТО в отчёте обязано быть.
 *
 * ВСТРОЕННЫЕ СТРОКИ НАЗВАНЫ ЗАПРЕТНЫМИ ПРЯМО В ТЕКСТЕ, хотя их и стережёт сервер. Отказ по
 * объекту повтором не чинится, и модель, не знающая правила заранее, потратила бы на него
 * шаг — а шагов у прогона немного.
 */
export const GARDENER_BODY = `Ты — садовник словаря свойств. Раз в неделю приводишь его в порядок: сводишь дубли и рассказываешь владельцу о том, что в нём залежалось.

Шаг 1. Дубли.
- Возьми каталог свойств владельца: property_catalog без фильтров (при большом словаре — по слову, property_catalog с q).
- Ищи пары, у которых РАЗНЫЕ key, но один и тот же смысл: сравнивай подпись (label) и описание (description), а не написание ключа. «Усилие» и «Уровень усилия» — дубль; «Срок» и «Дата начала» — нет.
- Сливать можно только СВОИ свойства владельца — те, чей key начинается на «user/». Свойства с key на «orbis/» встроены в систему: их не сливай ни источником, ни целью, сервер откажет и шаг пропадёт зря.
- Направление слияния: source — то, у которого меньше носителей и значений (usage), into — то, которое остаётся. При равенстве оставляй свойство с более понятной подписью.
- Слияние вызывай инструментом property_merge. Ответ «pending_confirmation» — это НЕ отказ: карточка ушла владельцу в пачку решений, он разберёт её сам. Продолжай работу и не повторяй тот же вызов.
- За один прогон предлагай не больше трёх слияний: пачка владельца не резиновая, а неразобранные карточки следующий прогон увидит в истории.

Шаг 2. Сироты.
- Возьми property_catalog с orphans: true — это свойства, которых не объявляет ни один аспект и у которых нет ни одного значения.
- Сам с ними ничего не делай: удалять и прятать свойства — решение владельца.

Шаг 3. Залежавшиеся предложения.
- Возьми property_catalog со status: "proposed" и olderThanDays: 14 — предложенные свойства, которые ждут решения больше двух недель.
- Их тоже не трогай: их судьбу решает владелец.

Отчёт (финальный текст хода, его владелец прочтёт на экране прогона):
- что предложил слить и почему («X» и «Y» — одно и то же, потому что …);
- список сирот подписями, с числом носителей и значений;
- список предложений старше 14 дней подписями, с возрастом в днях.
Если по какому-то из трёх разделов ничего не нашлось — так и напиши одной строкой, а не пропускай раздел молча: «сирот нет» — это тоже результат недельного обхода.`;

export interface GardenerSeedResult {
  /** Сущность садовника создана ЭТИМ вызовом; false — уже была. */
  seeded: boolean;
  id: string;
}

/**
 * Сев садовника — ОТДЕЛЬНОЙ транзакцией, ПОСЛЕ коммита онбординга (рулинг Р-17-1).
 *
 * ПОЧЕМУ НЕ ВНУТРИ `seedOnboarding`. `seedOnboarding` работает внутри уже открытой
 * транзакции (`Tx`) и первым делом берёт `SELECT … FOR UPDATE` на строке настроек, а
 * `execute` принимает `Db` и открывает транзакцию САМ — на другом соединении. Вложенный
 * вызов встал бы насмерть на замке, который держит объемлющая транзакция: не «медленно», а
 * дедлок на первом заходе владельца.
 *
 * ПОЧЕМУ ПРОБА ПО PK, А НЕ GUARD НАСТРОЕК. Guard отвечает на вопрос «онбординг уже был?», а
 * здесь нужен ответ на «садовник уже есть?». Разойтись они могут на одном сценарии, и он не
 * теоретический: транзакция онбординга закоммитилась, `execute` упал (кончилось соединение,
 * отказ валидатора — что угодно) — владелец остался с графом без садовника, а повторный
 * заход по guard'у ответил бы «онбординг уже был» и не досеял бы его НИКОГДА. Проба по PK
 * этот сценарий закрывает сама и заодно делает функцию досевом для тех, кто засиден раньше.
 *
 * ЖУРНАЛА У СЕВА НЕТ (синк не передаётся — `execute` берёт NOOP): сид — системная
 * инициализация, а не правка владельца, и решение 6 плана онбординга («15 audit-сообщений
 * при регистрации — шум в ленте») распространяется на него целиком. Побочное следствие
 * важнее самой ленты: без записи в журнале сев не становится «последним действием», и
 * `undo_last` не может снять садовника вместе с доверенностью.
 *
 * `mechanism: 'seed'` (§А4-4) — вторая ось операции: канал (`source: 'system'`) отвечает,
 * откуда пришла запись, механизм — чем она сделана. `source: 'system'` выбран ещё и потому,
 * что `'routine'` включил бы запрет по объекту (`assertRoutineUntouchable`): рутину не
 * заводит рутина, её заводит система при первом заходе владельца.
 */
export async function seedGardener(
  db: Db,
  ownerId: string,
  clock: () => Date = () => new Date(),
): Promise<GardenerSeedResult> {
  const id = seedRoutineId(ownerId, GARDENER_SLUG);
  const existing = await withIdentity(db, ownerId, (tx) =>
    tx.execute(sql`SELECT 1 FROM entities WHERE id = ${id}::uuid AND owner_id = ${ownerId}`),
  );
  if (existing.length > 0) return { seeded: false, id };

  const r = await execute(db, {
    actorUserId: ownerId,
    actorKind: 'owner',
    source: 'system',
    mechanism: 'seed',
    operations: [
      {
        tool: 'entity_create',
        input: {
          id,
          title: GARDENER_TITLE,
          emoji: '🌿',
          body: GARDENER_BODY,
          // Тег `routine` — тот же, которым владелец находит рутины в Browser; смарт-лист
          // «Рутины» ищет их по аспекту, но тег остаётся человеческим адресом (§7.6).
          tags: ['routine'],
          aspects: ['orbis/routine'],
          props: { ...GARDENER_PROPS },
        },
      },
    ],
    clock,
  });
  if (!r.ok) {
    // Отказ НЕ глушится: посеянная наполовину доверенность хуже отсутствующей, а вызывающий
    // (ручка онбординга) обязан узнать, что сид не полон, — повторный заход досеет садовника
    // пробой по PK выше.
    throw new Error(`сев садовника словаря: ${r.error.code} ${r.error.message}`);
  }
  return { seeded: true, id };
}
