// Read-only замер корпуса тел ПЕРЕД необратимой конверсией (`backfill-body-doc`).
//
// Живёт рядом с бэкфиллом и по той же причине, по какой у бэкфилла вынесен цикл: прод-операция
// (`scripts/ops.ts audit-bodies`) ходит в базу сырым пулом, и дословная копия арифметики в
// скрипте осталась бы НЕ ПОКРЫТОЙ тестом. Здесь и порционность, и все девять счётчиков
// проверяются без базы вовсе.
import {
  type BodyDoc,
  bodyRefsFromDoc,
  canonicalizeBody,
  losesWord,
  projectionKeepsEverything,
  serializeBody,
} from '@orbis/shared/doc';
import type { JSONContent } from '@tiptap/core';
import type { RoleAccess } from './backfill-body-doc';

/**
 * Строка корпуса. `body` может прийти NULL — см. `?? ''` ниже. `bodyDoc` читается ради
 * ПОСТ-проверки: до конверсии он всюду NULL, после неё обязан быть заполнен и согласован
 * с `body` (ре-ревью раунда 3, п.5).
 */
export type AuditRow = {
  id: string;
  body: string | null;
  bodyDoc: unknown;
  /** Исходное тело до конверсии. Читается ради проверки, что страховка обратимости РЕАЛЬНО
   *  заполнена: всё заявление «процедура обратима» держится на ней, а проверки не было. */
  bodyBeforeDoc: string | null;
};

/**
 * Минимальный доступ к БД: взять порцию тел по курсору. Единственный SQL команды — SELECT,
 * она не пишет ничего.
 */
export interface AuditIo {
  /** Строки с `id > afterId`, по возрастанию id, не больше `limit` штук. */
  selectBatch(limit: number, afterId: string): Promise<AuditRow[]>;
}

/**
 * Размер порции. Здесь он не про блокировки (запросов на запись нет вовсе), а про память:
 * прежняя реализация тянула ВЕСЬ корпус одним `SELECT body FROM entities` — на замере,
 * который делается непосредственно перед необратимой операцией, это лишний риск, тем более
 * что сам бэкфилл порционный по осознанной причине (итоговое ревью, находка 7).
 */
export const AUDIT_BATCH = 200;

/** Начало курсора: меньше любого существующего uuid (та же константа, что у бэкфилла). */
const ID_START = '00000000-0000-0000-0000-000000000000';

/** «Нетривиальное» тело: несёт ссылку на сущность или смарт-лист. Флага `g` нет намеренно —
 *  у глобального регэкспа `test` тащит lastIndex между вызовами и через строку врал бы. */
const NONTRIVIAL_RE = /\[\[entity:|\{\{query:/i;

/**
 * Одинокий абзац из `&nbsp;`/U+00A0 и лишние пустые строки — доброкачественный шум, который
 * вычитается ПЕРЕД сверкой двух проходов канона.
 *
 * Без вычета кран «канон неустойчив» стал бы постоянно ненулевым сразу после выхода редактора
 * пользователям: markdown не умеет выражать пустой абзац, поэтому сериализатор печатает
 * `&nbsp;` за каждый ВТОРОЙ подряд пустой абзац — то есть за три нажатия Enter. Кран, всегда
 * красный на живой системе, читать перестают, и он перестаёт быть краном (ре-ревью раунда 5).
 *
 * Вычет узкий и проверен пробой: он гасит все пять бытовых расстановок пустых абзацев (внутри,
 * в начале, в конце, два/три/четыре подряд) и НЕ гасит ни одной настоящей неустойчивости —
 * вставка из одних пробелов во всех четырёх формах по-прежнему поднимает кран. На корпусе из
 * 37 тел вердикт изменился ровно у двух — обоих из этого семейства.
 */
const NBSP_PARA = /(^|\n)[ \t]*(?:&nbsp;| )[ \t]*(?=\n|$)/g;
const settle = (s: string): string =>
  s
    .replace(NBSP_PARA, '$1')
    .replace(/\n{3,}/g, '\n\n')
    .replace(/^\n+|\n+$/g, '');

/**
 * Все rawBlock-узлы дерева НА ЛЮБОЙ ГЛУБИНЕ.
 *
 * Плоский фильтр по верхнему уровню (как в плане) сегодня дал бы тот же ответ: parseBody
 * кладёт raw только детьми `doc` — проверено пробой на семнадцати формах разметки (html-блок,
 * картинка в абзаце, reference-определение, черта в ячейке таблицы, цитата и список с
 * непонятым содержимым — все дали глубину 1). Но rawBlock объявлен обычным block-узлом, то
 * есть законен внутри цитаты или элемента списка, и документ, прошедший через редактор, может
 * его туда положить. Обход всего дерева стоит копейки, а метрика перестаёт зависеть от места
 * узла — на замере перед необратимой конверсией это дешёвая страховка.
 *
 * Второе назначение — сам факт «есть raw»: сравнение `JSON.stringify(doc).includes('"rawBlock"')`
 * отвечает на этот вопрос лишь приблизительно (оно ищет строку в сериализации, а не узел
 * в дереве), а здесь точный ответ получается тем же обходом бесплатно.
 */
function collectRawBlocks(node: JSONContent, out: JSONContent[] = []): JSONContent[] {
  if (node.type === 'rawBlock') out.push(node);
  for (const child of node.content ?? []) collectRawBlocks(child, out);
  return out;
}

/**
 * Итог замера. Числа — стоп-кран перед конверсией: заметная доля raw или ненулевые ссылки
 * внутри raw означают, что до бэкфилла надо расширять белые списки токенов
 * (KNOWN_BLOCK/KNOWN_INLINE), а не запускать его.
 */
export type AuditResult = {
  /** Тел всего. */
  total: number;
  /** Тел, у которых канонизация изменит `body`. */
  changed: number;
  /**
   * СТОП-КРАН №1: тел, на которых канон НЕУСТОЙЧИВ — `canon(canon(body)) !== canon(body)`.
   *
   * `changed` на эту роль не годится и никогда не годился: канон законно нормализует разметку
   * (`*`→`-`, `__`→`**`, выравнивание таблиц, обрезка хвостовых переводов строки), и на живом
   * корпусе это число велико и неинформативно — в выборке ре-ревью из 45 бытовых тел канон
   * менял 11. Неустойчивость же означает, что второй проход даёт не то, что первый: тело
   * «дрожит», и необратимая конверсия зафиксирует ПРОИЗВОЛЬНЫЙ кадр этой дрожи.
   */
  unstable: number;
  /**
   * СТОП-КРАН №2: тел, у которых канонизация ТЕРЯЕТ написанное — непробельный символ или
   * ссылку. Тот же вопрос, что задаёт страховка записи, только с другого конца: там документ
   * приходит из редактора, здесь собирается из `body`. Ловит класс, который «неустойчивость»
   * пропускает: порчу, которая случается один раз и дальше стабильна.
   */
  lossy: number;
  /** Тел, которые получат хотя бы один rawBlock. */
  withRaw: number;
  /** Тел, у которых ссылка на сущность лежит ВНУТРИ raw-блока. */
  refsInRaw: number;
  /** Тел со ссылкой или смарт-листом — тех, которым есть что терять при конверсии. */
  nontrivial: number;
  /** Тел, на которых конверсия бросила исключение. */
  failed: number;
  /**
   * СТОП-КРАН №3, единственный про ПЕРВЫЙ разбор: тел, из которых по дороге в канон пропало
   * слово. Прочие краны считают ПОСЛЕ первого разбора и к этому классу слепы по построению,
   * а необратимый шаг бэкфилла — именно первый разбор.
   *
   * ЧТО ОН ЗНАЧИТ ПОСЛЕ РАУНДА 7. Разбор больше не решает по словам — он спрашивает СТРУКТУРУ
   * (`blockKeepsItsShape`), и это разные вопросы, а не один. Поэтому счётчик остаётся ВТОРЫМ,
   * НЕЗАВИСИМЫМ замером: структурный счёт слеп к потере ВНУТРИ сохранённого листа (лексер
   * обрезает лишние ячейки рваной строки ещё до нас — лист тот же), а словесный её видит.
   *
   * До раунда 7 счётчик и правда был близок к тавтологии: разбор гарантировал ТОТ ЖЕ предикат
   * поблочно, а целое строго слабее части — слово, потерянное в третьем блоке, «находилось» в
   * седьмом. Тогда это было верно; теперь предикаты разные, и число снова несёт информацию.
   */
  lostWords: number;
  /**
   * ПОСТ-ПРОВЕРКА, часть 1: тел без документа (`body_doc IS NULL`). До конверсии это весь
   * корпус, ПОСЛЕ неё обязан быть ноль — иначе конверсия не доехала.
   */
  withoutDoc: number;
  /**
   * ПОСТ-ПРОВЕРКА, часть 2: тел, у которых пара разошлась — `body !== serializeBody(body_doc)`.
   *
   * Заведена потому, что повторный прогон стоп-кранов после бэкфилла ВАКУУМЕН по построению
   * (ре-ревью раунда 3, п.5): после конверсии `body` уже канон, а `unstable` был нулём и на
   * шаге «до», значит будет нулём при любом исходе. Настоящая пост-проверка — несущий инвариант
   * хранения, а его до сих пор не читал никто: аудит `body_doc` не открывал вовсе.
   */
  pairBroken: number;
  /**
   * СТОП-КРАН №4: строк, у которых документ есть, а СТРАХОВКИ ОБРАТИМОСТИ нет
   * (`body_doc IS NOT NULL AND body_before_doc IS NULL`).
   *
   * Без этого числа всё заявление «процедура больше не необратима» ничем не проверено: если
   * миграция не накатилась, если ops запущен из старой сборки, если строку успел сконвертировать
   * путь ЗАПИСИ (редактор или модель) между миграцией и переносом — владелец досчитает до конца
   * по зелёным числам, останется без страховки и уже получит разрешение не хранить бэкап
   * (ре-ревью раунда 6, п.3).
   */
  convertedWithoutBackup: number;
  /**
   * `id` строк, поднявших ЛЮБОЙ стоп-кран, — не больше FLAGGED_LIMIT штук.
   *
   * Без них регламентный шаг «стоп и разбор конкретного тела» НЕИСПОЛНИМ: по счётчику «1»
   * человек не найдёт строку в корпусе на тысячи записей, а тот, кому нечем разбираться, кран
   * обойдёт — это свойство конструкции, а не догадка про людей (ре-ревью раунда 5).
   *
   * Приватность не страдает: uuid — не персональные данные, а тела и всё, что к ним ведёт,
   * из процесса по-прежнему не выходят. Список ограничен, чтобы больной корпус не вывалил
   * сотню тысяч строк в транскрипт.
   */
  flagged: Array<{ id: string; gates: string[] }>;
};

/** Сколько id печатать: для разбора нужен вход в корпус, а не весь его список. */
export const FLAGGED_LIMIT = 50;

/**
 * Код возврата замера: 0 — можно смотреть на числа, 1 — смотреть НЕ НА ЧТО или найдена беда.
 *
 * Проверка роли здесь ОБЯЗАТЕЛЬНА и ровно по той же причине, по какой она есть у бэкфилла
 * (находка M-2): под FORCE RLS роль без `BYPASSRLS` видит ноль строк молча, и оба стоп-крана
 * читаются нулями. Для бэкфилла это давало ложный «успех», а здесь — хуже: здесь ЧИСЛО И ЕСТЬ
 * РЕШЕНИЕ, то есть человек получал бы зелёный свет ровно тогда, когда аудит ничего не увидел
 * (ре-ревью раунда 3, п.1).
 *
 * `withoutDoc` в гейт НЕ входит: до конверсии он законно равен всему корпусу. Его сверяет
 * человек — нулём он обязан стать только на прогоне ПОСЛЕ бэкфилла.
 */
export function auditExitCode(who: RoleAccess, r: AuditResult): number {
  if (!who.bypassRls) return 1;
  return r.unstable > 0 ||
    r.lossy > 0 ||
    r.lostWords > 0 ||
    r.failed > 0 ||
    r.pairBroken > 0 ||
    r.convertedWithoutBackup > 0
    ? 1
    : 0;
}

/**
 * Строки для печати списка виновных — ОТДЕЛЬНОЙ функцией, чтобы их можно было проверить тестом.
 *
 * Прежняя печать жила прямо в `scripts/ops.ts`, перебирала массив объектов как массив строк и
 * выдавала `[object Object]`: шаг регламента «взять напечатанные id» был неисполним, а сьют
 * оставался зелёным, потому что проверял СТРУКТУРУ результата, а не вывод (ре-ревью раунда 7,
 * Д3). Прод-обёртка тестами не покрыта по построению — значит всё, что можно из неё вынести,
 * должно быть вынесено.
 */
export function formatFlagged(flagged: AuditResult['flagged']): string[] {
  return flagged.map((row) => `  ${row.id}  — ${row.gates.join(', ')}`);
}

/**
 * Считает агрегаты по корпусу. Тела НЕ печатаются и НЕ покидают процесс ни в каком виде:
 * это личные записи, а вывод команды попадает в транскрипты и отчёты. `id` выбирается ТОЛЬКО
 * ради курсора порций и ради списка `flagged` — ни одному СЧЁТЧИКУ он не нужен.
 *
 * (До раунда 5 здесь стояло «и никуда не идёт». После того как аудит начал печатать id
 * виновных строк, это перестало быть правдой, и утверждение исправлено: наружу не выходят
 * ТЕЛА, а идентификаторы выходят — намеренно, иначе разбор по кранам неисполним.)
 *
 * `canon` параметром, а не жёстко: единственный способ проверить ветку `failed` — подсунуть
 * конверсию, которая бросает. Настоящая (`canonicalizeBody`) не бросила ни разу на 23
 * недружелюбных телах, поэтому иначе счётчик остался бы утверждением без доказательства.
 */
export async function auditBodies(
  io: AuditIo,
  canon: (markdown: string) => { doc: BodyDoc; body: string } = canonicalizeBody,
): Promise<AuditResult> {
  const result: AuditResult = {
    total: 0,
    changed: 0,
    unstable: 0,
    lossy: 0,
    withRaw: 0,
    refsInRaw: 0,
    nontrivial: 0,
    failed: 0,
    lostWords: 0,
    withoutDoc: 0,
    pairBroken: 0,
    convertedWithoutBackup: 0,
    flagged: [],
  };
  let afterId = ID_START;
  for (;;) {
    const rows = await io.selectBatch(AUDIT_BATCH, afterId);
    if (rows.length === 0) break;
    for (const row of rows) {
      result.total += 1;
      // Курсор двигается ВСЕГДА, в том числе на упавшей строке: иначе она вращала бы цикл.
      afterId = row.id; // выборка отсортирована по id, поэтому последний id порции — наибольший
      // Имя крана, а не голый факт: при нескольких ненулевых числах человек иначе получает
      // смесь строк и не знает, с чем идти к каждой (ре-ревью раунда 6).
      const gates: string[] = [];
      const flag = (hit: boolean, gate: string): boolean => {
        if (hit) gates.push(gate);
        return hit;
      };
      try {
        // `?? ''` — не про текущую схему (там body NOT NULL DEFAULT ''), а про то, что команда
        // ходит в ПРОД: его схема — та, что развёрнута, а не та, что в этом файле. NULL здесь
        // должен дать пустое тело, а не остановить замер на середине корпуса.
        const body = String(row.body ?? '');
        if (NONTRIVIAL_RE.test(body)) result.nontrivial += 1;
        // ПОСТ-проверка пары. Своим try — потому что на документе, непригодном по схеме,
        // serializeBody падает, и это тоже «пара сломана», а не «тело не разобралось».
        if (row.bodyDoc === null || row.bodyDoc === undefined) {
          result.withoutDoc += 1;
        } else {
          // Документ есть — значит строка уже сконвертирована. Тогда обязана быть и страховка
          // обратимости: её кладёт бэкфилл тем же UPDATE. Пусто — строку перевёл путь ЗАПИСИ
          // (редактор или модель) либо старая сборка ops, и восстановить её нечем.
          if (row.bodyBeforeDoc === null || row.bodyBeforeDoc === undefined) {
            result.convertedWithoutBackup += 1;
            gates.push('нет страховки обратимости');
          }
          try {
            if (flag(serializeBody(row.bodyDoc as BodyDoc) !== body, 'пара разошлась')) {
              result.pairBroken += 1;
            }
          } catch {
            result.pairBroken += 1;
            gates.push('пара разошлась');
          }
        }
        const { doc, body: canonical } = canon(body);
        if (canonical !== body) result.changed += 1;
        // Два стоп-крана. Второй прогон канона — единственная лишняя работа замера, и она того
        // стоит: именно эти числа решают, можно ли пускать необратимую конверсию.
        if (flag(settle(canon(canonical).body) !== settle(canonical), 'канон неустойчив')) {
          result.unstable += 1;
        }
        if (flag(!projectionKeepsEverything(doc, canonical), 'теряет текст или ссылку')) {
          result.lossy += 1;
        }
        // Единственная проверка ПЕРВОГО разбора — того шага, который бэкфилл делает необратимо.
        if (flag(losesWord(body, canonical), 'пропало слово')) result.lostWords += 1;
        const raws = collectRawBlocks(doc.doc);
        if (raws.length > 0) {
          result.withRaw += 1;
          // Ссылки ищем В САМИХ raw-узлах, а не разницей «всего минус дерево», как в плане:
          // bodyRefsFromDoc отдаёт МНОЖЕСТВО, поэтому ссылка, упомянутая и в прозе, и внутри
          // raw, разницу не увеличивает — тело со ссылкой в raw считалось бы чистым
          // (воспроизведено пробой). Прямой вопрос «есть ли ссылка в raw» ответа не теряет.
          if (bodyRefsFromDoc({ type: 'doc', content: raws }).length > 0) result.refsInRaw += 1;
        }
      } catch {
        // Одно неразобранное тело не должно рушить замер: аудит и заведён затем, чтобы такие
        // тела ПОСЧИТАТЬ. Само тело в вывод не идёт даже в этой ветке.
        result.failed += 1;
        gates.push('упало на парсе');
      }
      if (gates.length > 0 && result.flagged.length < FLAGGED_LIMIT) {
        result.flagged.push({ id: row.id, gates });
      }
    }
    if (rows.length < AUDIT_BATCH) break; // неполная порция — корпус исчерпан, лишний SELECT не нужен
  }
  return result;
}
