// Разовая конверсия существующих тел в структурную форму. Порциями: тел может быть много, а
// один долгий UPDATE держал бы блокировки дольше нужного.
//
// Не «миграция данных внутри SQL-миграции» намеренно: конверсию делает JS-парсер
// (@orbis/shared/doc), внутри postgres его нет. Запускается через `bun scripts/ops.ts` после
// наката 0007; всё, что бэкфилл не догнал, сервер конвертирует лениво при первом чтении —
// колонка nullable ровно ради этого.
//
// Команда работает по ЖИВОЙ базе: владелец и агенты пишут в неё одновременно с прогоном.
// Отсюда две несущие конструкции ниже — CAS по исходному телу (чтобы не затереть чужую правку)
// и курсор по id (чтобы пропущенная строка не закрутила цикл).
import { type BodyDoc, canonicalizeBody } from '@orbis/shared/doc';
import { sql } from 'drizzle-orm';
import type { Db } from './client';

/** Строка, которую бэкфилл берёт в работу. `body` может прийти NULL — см. `?? ''` ниже. */
export type BackfillRow = { id: string; body: string | null };

/**
 * Минимальный доступ к БД, который нужен циклу: взять порцию неконвертированных тел, записать
 * результат по одной строке и посчитать остаток.
 *
 * Зачем интерфейс. Цикл обязан существовать в ЕДИНСТВЕННОМ экземпляре: тест ходит в локальную
 * базу через drizzle, а прод-операция — через сырой пул `scripts/ops.ts`, и дословная вторая
 * копия цикла была бы НЕ ПОКРЫТА тестом (ревью И16) — то есть разошлась бы с проверенной на
 * первой же правке размера порции. Заодно интерфейс даёт шов: поведение порций, курсора и
 * пропусков проверяется без базы вовсе.
 */
export interface BackfillIo {
  /** Строки с `body_doc IS NULL` и `id > afterId`, по возрастанию id, не больше `limit` штук. */
  selectBatch(limit: number, afterId: string): Promise<BackfillRow[]>;
  /**
   * Пишет обе колонки строки, НО только если её тело всё ещё равно `expectedBody`.
   * Возвращает `false`, если строку тронули с момента выборки и запись не состоялась.
   */
  writeRow(row: {
    id: string;
    doc: BodyDoc;
    body: string;
    expectedBody: string | null;
  }): Promise<boolean>;
  /** Сколько тел ещё без документа. Считается один раз, в конце прогона. */
  countPending(): Promise<number>;
}

/** Размер порции. Меняется в ОДНОМ месте — второй копии цикла нет. */
const BATCH = 200;

/** Начало курсора: меньше любого существующего uuid. */
const ID_START = '00000000-0000-0000-0000-000000000000';

/**
 * Итог прогона. Три числа, а не одно, — чтобы «ничего не сделано» нельзя было принять за успех:
 * при роли без BYPASSRLS выборка пуста, и одинокое `сконвертировано: 0` выглядело бы ровно как
 * успешный прогон по уже сконвертированному корпусу (ревью M-2).
 */
export type BackfillResult = {
  /** Строк переписано. */
  done: number;
  /** Строк пропущено, потому что их тело изменилось во время прогона (CAS не сошёлся). */
  skipped: number;
  /** Строк с `body_doc IS NULL` осталось после прогона. */
  pending: number;
};

/**
 * Конвертирует тела без документа и возвращает три числа прогона.
 *
 * Идемпотентна: выборка идёт по `body_doc IS NULL`, поэтому сконвертированная строка сама
 * покидает очередь, а повторный запуск честно возвращает `done: 0`.
 *
 * Ошибку конверсии НЕ глотает — и это осознанно. Каждая строка пишется своим UPDATE в
 * автокоммите (`withDb` не открывает транзакцию), так что падение на середине оставляет уже
 * сконвертированное сконвертированным, а остальное — с NULL: чинится парсер, команда
 * запускается снова. Оговорка честности: строка, на которой парсер падает, обрывает и ВЕСЬ
 * оставшийся хвост корпуса — до неё дойдёт, дальше нет.
 * (Пробой на 23 недружелюбных телах — html, reference-определения, черта в ячейке, сноски,
 * одинокий суррогат, 200 уровней вложенности — canonicalizeBody не бросил ни разу.)
 */
export async function backfillBodyDoc(io: BackfillIo): Promise<BackfillResult> {
  let done = 0;
  let skipped = 0;
  let afterId = ID_START;
  for (;;) {
    const rows = await io.selectBatch(BATCH, afterId);
    if (rows.length === 0) break;
    for (const row of rows) {
      // `?? ''` — не про текущую схему (там body NOT NULL DEFAULT ''), а про то, что команда
      // ходит в ПРОД: его схема — та, что развёрнута, а не та, что в этом файле.
      const { doc, body } = canonicalizeBody(String(row.body ?? ''));
      // body тоже выравнивается до канона: FTS не сдвигается (проверено сверкой to_tsvector),
      // сиды не меняются (они канон — seed-canon.test.ts), а инвариант пары
      // «body === serializeBody(body_doc)» держится с первого дня, а не «после первого
      // пересохранения». Инвариант этот про СОГЛАСОВАННОСТЬ пары, а не про верность канона
      // оригиналу: что канон ничего не теряет — предмет Задачи 2 и команды audit-bodies.
      const written = await io.writeRow({ id: row.id, doc, body, expectedBody: row.body });
      if (written) {
        done += 1;
      } else {
        // Строку тронули между выборкой и записью — оставляем как есть. Это ПРАВИЛЬНЫЙ исход:
        // затирать свежий текст владельца каноном прочитанного старого нельзя, а `body_doc`
        // у неё останется NULL, и ленивая конверсия при первом чтении её догонит.
        skipped += 1;
      }
      // Курсор двигается ВСЕГДА — и на записанной строке, и на пропущенной. Без этого
      // пропущенная строка снова попадала бы в выборку `body_doc IS NULL` и вращала бы цикл
      // вечно. Курсор выбран вместо «копить пропущенные id и исключать их из выборки» (растёт
      // без границы и утяжеляет каждый запрос) и вместо «сорваться на порции без прогресса»
      // (порция из 199 записанных и одной пропущенной прогресс имеет, поэтому такой критерий
      // всё равно перечитывал бы пропущенные снова и снова, а на порции, где владелец правит
      // активно, обрывал бы конверсию всего хвоста корпуса). Курсор же даёт строгую гарантию:
      // каждая строка осматривается за прогон ровно один раз, при любом числе пропусков.
      afterId = row.id; // выборка отсортирована по id, поэтому последний id порции — наибольший
    }
    if (rows.length < BATCH) break; // неполная порция — очередь исчерпана, лишний SELECT не нужен
  }
  return { done, skipped, pending: await io.countPending() };
}

/**
 * Всё, что нужно адаптеру от drizzle, — выполнить запрос. Шире, чем `Db`, намеренно: под этот
 * тип подходит и объект ТРАНЗАКЦИИ (`db.transaction(async (tx) => …)`), а значит тест умеет
 * прогнать настоящий SQL по временно изменённой схеме и откатить всё до байта.
 */
export type BackfillExecutor = Pick<Db, 'execute'>;

/** Под кем команда пришла в базу и видит ли она строки вообще. */
export type RoleAccess = { role: string; bypassRls: boolean };

/**
 * Кто мы в базе. Единственное, что отличает «корпус уже сконвертирован» от «роль не видит
 * корпуса»: в обоих случаях счётчики прогона — нули (ревью M-2).
 *
 * Зачем это вообще нужно: на `entities` включён FORCE ROW LEVEL SECURITY с политикой
 * `owner_id = auth.uid()`, а прямое подключение никакого `auth.uid()` не выставляет. Роль,
 * у которой ЕСТЬ гранты на таблицу, но НЕТ `BYPASSRLS`, видит ровно ноль строк — молча,
 * без единой ошибки (воспроизведено пробой под ролью `authenticated`: `count(*)` вернул 0
 * при непустой таблице, а бэкфилл отчитался `{done:0, skipped:0, pending:0}`).
 */
export async function describeRoleAccess(db: BackfillExecutor): Promise<RoleAccess> {
  const rows = await db.execute(
    sql`SELECT current_user::text AS role,
        coalesce((SELECT rolbypassrls FROM pg_roles WHERE rolname = current_user), false)
          AS bypass_rls`,
  );
  const row = rows[0] as { role: string; bypass_rls: boolean };
  return { role: row.role, bypassRls: row.bypass_rls };
}

/**
 * Адаптер поверх drizzle. Его же использует прод-операция (`scripts/ops.ts backfill-body-doc`),
 * обернув сырой пул из `withDb` — так на проде исполняется ровно тот SQL, который прогнал тест.
 */
export function drizzleBackfillIo(db: BackfillExecutor): BackfillIo {
  return {
    selectBatch: async (limit, afterId) =>
      (await db.execute(
        sql`SELECT id, body FROM entities
            WHERE body_doc IS NULL AND id > ${afterId}::uuid
            ORDER BY id LIMIT ${limit}`,
      )) as unknown as BackfillRow[],

    writeRow: async ({ id, doc, body, expectedBody }) => {
      // CAS по исходному телу. Без него бэкфилл затирал бы правку, сделанную владельцем или
      // агентом между выборкой порции и записью этой строки (окно — до секунды: последняя
      // строка порции ждёт обработки предыдущих 199). Воспроизведено пробой: правка владельца
      // молча заменялась каноном прочитанного старого тела.
      //
      // IS NOT DISTINCT FROM, а не `=`: тело может быть NULL (схема прода — та, что развёрнута),
      // а `NULL = NULL` даёт NULL, то есть строка не совпала бы НИКОГДА и тихо копилась бы
      // в пропущенных.
      const rows = await db.execute(
        sql`UPDATE entities SET body_doc = ${JSON.stringify(doc)}::jsonb, body = ${body}
            WHERE id = ${id} AND body IS NOT DISTINCT FROM ${expectedBody}::text
            RETURNING id`,
      );
      // RETURNING + длина, а не rowCount драйвера: форма ответа у drizzle/postgres-js зависит
      // от версии, а число вернувшихся строк — нет.
      return rows.length === 1;
    },

    countPending: async () => {
      const rows = await db.execute(
        sql`SELECT count(*)::int AS n FROM entities WHERE body_doc IS NULL`,
      );
      return (rows[0] as { n: number }).n;
    },
  };
}
