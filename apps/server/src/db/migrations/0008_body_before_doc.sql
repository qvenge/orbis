-- Страховка обратимости разовой конверсии тел (`backfill-body-doc`).
--
-- Колонка хранит ИСХОДНОЕ тело до канонизации и заполняется тем же UPDATE, что и конверсия.
-- Ничем не читается в рантайме: она нужна ровно затем, чтобы восстановление одной записи было
-- одним UPDATE, а не подъёмом дампа всей схемы в отдельную базу.
--
-- Живёт под той же RLS, что и сама запись (политика на `entities` уже есть, отдельной не надо).
-- Снимается отдельной миграцией после того, как перенос признан удачным.
ALTER TABLE "entities" ADD COLUMN "body_before_doc" text;
