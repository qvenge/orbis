-- 0013_routine_scheduler_rls.sql
-- Список владельцев для тика планировщика рутин (V1.13, инвариант 14).
--
-- Планировщик — единственный путь в системе, у которого НЕТ владельца: он просыпается по
-- таймеру и должен узнать, кого вообще обходить. Всё остальное он делает уже под
-- withIdentity(владелец), где графом заведует обычная политика owner_owns_row (0001).
-- Bypass RLS не вводится ни здесь, ни где-либо ещё: у orbis_app стоит NOBYPASSRLS
-- (scripts/setup-db.ts), и это не должно меняться.
--
-- Почему источник — user_settings, а не entities. Список владельцев можно было бы взять
-- и из графа (SELECT DISTINCT owner_id FROM entities), но тогда служебной роли пришлось бы
-- открыть таблицу, в которой лежат ТЕЛА рутин, назначений и всего остального. Строка
-- настроек заводится онбордингом ровно одна на владельца (§7.3) — то же множество
-- владельцев, но у́же по данным: планировщик не получает доступа ни к одной их записи.
--
-- Почему USING (true) и почему её нечем сузить. Под orbis_app auth.uid() пуст —
-- request.jwt.claims ставит только withIdentity, а у тика владельца нет по построению.
-- Любое условие вида owner_id = auth.uid() под этой ролью всегда ложно, то есть узкая
-- политика закрыла бы сам обход. Тот же размен и та же форма, что у server_manages_grants
-- в 0005: под служебной ролью RLS не подстраховывает предикаты, границу держит то, что
-- DATABASE_URL с ролью orbis_app не покидает сервер.
--
-- FOR SELECT, а не FOR ALL (в отличие от 0005): планировщик настройки только читает.
-- Записывает их владелец под authenticated — там политика owner_owns_row без изменений.
CREATE POLICY scheduler_reads_owner_list ON user_settings FOR SELECT TO orbis_app USING (true);
