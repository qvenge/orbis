// apps/server/src/registry/version.ts
//
// ВЕРСИЯ РЕЕСТРОВ (§А10-1) — две половины одного числа и единственное место, знающее, где
// каждая лежит: системную (`registry_system.version`) двигает сид, половину владельца
// (`user_settings.registry_version`) — любая мутация ЕГО реестров, в ТОЙ ЖЕ транзакции.
//
// Зачем инвариант «в той же транзакции». Версия — ключ процессного кеша эффективных
// определений (`registry/cache.ts`). Мутация, закоммитившая строку реестра БЕЗ инкремента,
// оставляет кеш на прежнем ключе — и процесс продолжает валидировать записи, собирать
// `attach_*`-тулы и рисовать форму по определению, которого в базе уже нет. Ошибка при этом
// молчаливая: ни отказа, ни лога, только «почему-то старое поле». Поэтому инкремент не
// «желателен рядом», а обязан идти тем же коммитом: либо видны обе правки, либо ни одной.
//
// Инкремент — UPSERT, а не UPDATE. Строки настроек у владельца может не быть вовсе (§А10-1
// не обещает её существования: онбординг мог не проходиться), и `UPDATE … WHERE owner_id`
// в этом случае трогает НОЛЬ строк — то есть тихо не двигает версию и оставляет кеш на
// прежнем ключе ровно в том случае, ради которого функция и заведена. Отличить «версия
// поднята» от «строки нет» по числу задетых строк невозможно постфактум, поэтому строка
// создаётся на месте со всеми умолчаниями колонок.
import { sql } from 'drizzle-orm';
import type { Tx } from '../db/with-identity';

/**
 * Кому обе функции годятся: транзакции исполнителя (`Tx`) И голому подключению (`Db`) —
 * админскому сиду, скриптам `ops.ts` и фикстурам тестов, у которых транзакции на руках нет.
 * Тип сужен до одного метода намеренно: версия реестра — это два точечных запроса, и
 * функция, которой отдали бы весь клиент, однажды начала бы делать что-то ещё.
 *
 * Фикстуры ходят ЗДЕСЬ ЖЕ, а не мимо: прямой INSERT строки реестра в тесте — такая же
 * мутация реестра, как операция владельца, и кеш (`cache.ts`) отличает их только версией.
 * Отдельного «сброса кеша для тестов» нет намеренно — он был бы вторым механизмом
 * инвалидации, которым в бою никто не пользуется, то есть тесты зеленели бы путём, которого
 * в проде нет.
 */
export type RegistrySqlRunner = Pick<Tx, 'execute'>;

/**
 * Обе половины версии плюс признак «эта транзакция уже писала».
 *
 * Имена полей — те же, что у снимка (`RegistrySnapshot.ownerVersion`/`systemVersion`), а
 * не короткие `owner`/`system`: версия ездит через wire (`registryVersionOf`, `entity.get`,
 * `registry.effective`), и второе имя для того же числа означало бы переименовывающий
 * переходник на каждой границе — ровно то место, где половины однажды меняются местами.
 *
 * `txHasWritten` едет ТЕМ ЖЕ запросом, а не отдельным: вопрос «под каким ключом класть
 * снимок в кеш» и вопрос «можно ли его туда класть вообще» решаются в один момент и по
 * одному состоянию транзакции; два запроса дали бы два разных момента (см. `cache.ts`).
 */
export interface RegistryVersions {
  ownerVersion: number;
  systemVersion: number;
  /**
   * `pg_current_xact_id_if_assigned() IS NOT NULL` — транзакции УЖЕ выдан xid, то есть она
   * что-то записала. Кеш это состояние обходит стороной (обоснование — докблок `cache.ts`,
   * раздел про откат бампа).
   */
  txHasWritten: boolean;
}

/**
 * Обе половины версии реестра ОДНИМ запросом — без самих словарей.
 *
 * Отдельный вход нужен читателям, которым словари не нужны вовсе: `entity.get` кладёт
 * версию в ответ, чтобы клиентский кеш реестра было чем инвалидировать (§А10-1), и грузить
 * ради одного числа 77 свойств, 13 аспектов и 11 ролей на каждое открытие записи было бы
 * дороже самой записи. `effectiveRegistry` зовёт этот же запрос — второго места, знающего,
 * ГДЕ лежат обе половины версии, быть не должно.
 *
 * Один запрос, а не три: обе половины — точечные чтения по первичному ключу, а признак
 * записи вообще не ходит в таблицы, и лишний round-trip по соединению транзакции стоит
 * дороже, чем два подзапроса в одном плане.
 */
export async function readRegistryVersions(
  tx: RegistrySqlRunner,
  ownerId: string,
): Promise<RegistryVersions> {
  const rows = (await tx.execute(sql`
    SELECT (SELECT version FROM registry_system WHERE id = 1) AS system_version,
           (SELECT registry_version FROM user_settings WHERE owner_id = ${ownerId}::uuid)
             AS owner_version,
           pg_current_xact_id_if_assigned() IS NOT NULL AS tx_has_written`)) as unknown as {
    system_version: number | null;
    owner_version: number | null;
    tx_has_written: boolean;
  }[];
  const row = rows[0];
  const systemVersion = row?.system_version;
  if (systemVersion === null || systemVersion === undefined) {
    // Системной строки не быть НЕ может: её кладёт миграция 0014. Молча подставить ноль
    // значило бы выдать «база без миграций» за «сида ещё не было».
    throw new Error('readRegistryVersions: в registry_system нет строки id=1 — база без 0014');
  }
  return {
    // Строки настроек может не быть вовсе (владелец не проходил онбординг) — это законный
    // случай, а не отказ: реестр у него ровно системный, и версия его половины нулевая.
    ownerVersion: row?.owner_version ?? 0,
    systemVersion: systemVersion,
    txHasWritten: row?.tx_has_written === true,
  };
}

/**
 * Поднять версию реестров владельца — В ТОЙ ЖЕ ТРАНЗАКЦИИ, ЧТО МУТАЦИЯ (§А10-1).
 *
 * Возвращает НОВОЕ значение — вызывающему оно нужно, чтобы не читать версию вторым
 * запросом (между инкрементом и SELECT'ом уместилась бы чужая мутация). С `base_version`
 * дельты это число не путать: там лежит СИСТЕМНАЯ версия, на которую дельта опиралась
 * (§А3-3), а здесь двигается половина владельца.
 *
 * Одна транзакция может звать функцию несколько раз (пачка операций реестра) — версия
 * вырастет на число вызовов. Это не проблема: наружу версия наблюдаема только как «то же
 * число или другое», и лишний шаг стоит одного промаха кеша, тогда как попытка «поднять
 * ровно один раз на транзакцию» потребовала бы состояния поверх tx — второй правды о том,
 * что уже произошло в базе.
 */
export async function bumpOwnerRegistryVersion(
  tx: RegistrySqlRunner,
  ownerId: string,
): Promise<number> {
  const rows = (await tx.execute(sql`
    INSERT INTO user_settings (owner_id, registry_version) VALUES (${ownerId}::uuid, 1)
    ON CONFLICT (owner_id)
      DO UPDATE SET registry_version = user_settings.registry_version + 1
    RETURNING registry_version`)) as unknown as { registry_version: number }[];
  const version = rows[0]?.registry_version;
  if (version === undefined) {
    // Недостижимо: UPSERT по PK либо вставляет, либо обновляет. Пустой RETURNING означал бы
    // отфильтрованную RLS строку — то есть мутацию чужого реестра, о которой нельзя молчать.
    throw new Error('bumpOwnerRegistryVersion: UPSERT не вернул строку (чужой owner_id?)');
  }
  return version;
}
