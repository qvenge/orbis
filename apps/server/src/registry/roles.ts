// Реестр РОЛЕЙ как подзапрос — для одного-единственного случая: когда эффективные строки
// нужны ВНУТРИ компилируемого SQL, а не на руках у кода.
//
// Такой случай ровно один и он не сводится к снимку: круг исполнителя (`agent-loop/queries.ts`,
// три места) фильтрует рёбра условием `r.role IN (…иерархические…)` прямо в большом запросе,
// и подставить туда список из снимка значило бы либо гнать N параметров, либо собирать SQL
// строкой. Всё остальное приложение берёт роли и свойства ИЗ СНИМКА
// (`registry/cache.ts`, `effectiveRegistry`).
//
// ПОЧЕМУ ЭТО НЕ ВТОРАЯ ПРАВДА И ГДЕ ЕЁ ГРАНИЦА. Правило разрешения коллизии здесь то же,
// что в снимке: своя строка владельца ПЕРЕКРЫВАЕТ встроенную (снимок добивается этого
// `ORDER BY owner_id NULLS FIRST` + перезаписью ключа Map, здесь —
// `DISTINCT ON (id) … ORDER BY owner_id DESC NULLS LAST`), и равенство запиннено
// `roles.test.ts` на живой базе.
//
// А вот ДЕЛЬТ (§А3-2) подзапрос не знает и знать не может: дельта — отдельная таблица,
// сложить её с определением умеет только `applyDeltas`. Для признака `hierarchical` это
// безразлично — форма дельты его не трогает (`aspectDeltaSchema`/`propertyDeltaSchema`
// правят подписи, состав аспекта и варианты select, но не флаги ролей). Появится дельта
// роли — этот подзапрос обязан уйти вместе с ней, а условие «роль иерархическая» переехать
// в снимок. Признак, по которому следующий читатель поймёт, что момент настал: в
// `applyDeltas` (`registry/deltas.ts`, ветка `row.targetKind !== 'aspect'`) появилась
// обработка цели `relation_role` вместо отказа `DELTA_TARGET_UNSUPPORTED`. Именно там
// живёт запрет — перечень `REGISTRY_DELTA_TARGET_KINDS` цель `relation_role` СОДЕРЖИТ
// (он повторяет CHECK таблицы) и сам по себе не отвергает ничего.
//
// Прежде здесь жил и близнец для СВОЙСТВ (`effectivePropertiesSql`): по нему секция
// «Связанное» брала подпись ссылочного ребра. Он снят гейт-ревью Задачи 14 — переопределение
// подписи встроенного свойства дельтой это прямое назначение `PropertyDelta` (Р19), а сырой
// запрос его не видел; `entity-read.ts` читает подписи из снимка.
import { type SQL, sql } from 'drizzle-orm';
import type { RegistrySnapshot } from './load';

/**
 * Подзапрос «эффективные строки реестра ролей»: по одной на id, своя перекрывает встроенную.
 *
 * Собственного фильтра по владельцу здесь НЕТ: все вызывающие идут под `withIdentity`, и
 * скоуп даёт RLS (`read_builtin_or_own`). Под админским подключением подзапрос вернул бы
 * строки всех владельцев — поэтому в сиды и миграции он не годится, там снимок.
 */
export function effectiveRolesSql(): SQL {
  return sql`(SELECT DISTINCT ON (id) *
                FROM relation_role_definitions
               ORDER BY id, owner_id DESC NULLS LAST)`;
}

/**
 * Подзапрос «id иерархических ролей» (§А4-3): `subitem`, `ticket`, `run`, `category-parent`
 * во встроенном реестре. Именно ПОДЗАПРОС, а не константа: роль с `hierarchical: true`
 * заводится операциями реестра (Задача 15), и список, написанный в коде, её не увидел бы
 * (находка 15 ревью плана).
 *
 * `envelope-binding` сюда не входит — конверт не родитель транзакции, он её счётчик
 * (Ч10-С1). Читателям, которым нужно прежнее множество старой колонки `relation_type`
 * (агрегаты бюджета), нужен `LEGACY_PARENT_ROLES`, а не этот список.
 */
export function hierarchicalRolesSql(): SQL {
  return sql`SELECT id FROM ${effectiveRolesSql()} d WHERE d.hierarchical`;
}

/** Тот же список из готового снимка — для путей, которые снимок уже держат. */
export function hierarchicalRoles(reg: RegistrySnapshot): string[] {
  return [...reg.roles.values()].filter((r) => r.hierarchical).map((r) => r.id);
}
