// Системный слой раннера рутины, версия 3 (реформа свойств, РП-18). Правило линейки то же,
// что у routine-v1 и routine-v2: ИЗМЕНЕНИЕ текста = НОВЫЙ файл routine-vN + новая фикстура;
// routine-v2.ts и его фикстура с этого момента не правятся ни байтом — они снимок того, что
// читала модель до реформы.
//
// ЗАЧЕМ ВЕРСИЯ. Реформа переселила структуру системы из кода в данные, и три места v2 стали
// описывать несуществующее:
//   1. `category_ref` — такого поля нет: категорию несёт свойство `orbis/finance_category`
//      (слияние `financial.category_ref` и `budget.category_ref`, §А8/В1);
//   2. шпаргалка грамматики учила ГОЛЫМ именам полей (`status=`, `due_date=`), а новый разбор
//      отвечает на них `UNKNOWN_FIELD` (`parse-ast.ts`): имена адресуются namespaced key;
//   3. запрет по объекту был назван доменными словами («сущности-рутины … прогоны»), а
//      исполнитель проверяет РЕЕСТРОВЫЕ аспекты цели — `orbis/routine`, служебный
//      `orbis/agent-run` и `orbis/assignment` (`executor/invariants.ts`,
//      `ROUTINE_UNTOUCHABLE_OBJECTS` ∪ аспект назначения). В v2 аспект прогона не был назван
//      вовсе: строка «Правила» перечисляла два аспекта из трёх, и отказ по третьему приезжал
//      модели без предупреждения.
//
// ЧТО ДОБАВЛЕНО СВЕРХ ПЕРЕВОДА:
//   а. конструкции грамматики, которых в шпаргалке v2 не было: `has=`, `via=`, сравнения,
//      правило кавычек у значения с пробелом и вход `ast` тула `entity_query` (§А5-4);
//   б. РУЛИНГ Р-19-1: своё свойство заводится со `status=proposed`. Основание — живой замер
//      Задачи 17: описание тула велит это дословно (`registry-tools.ts:100, :244`), и модель
//      всё равно завела 2 свойства из 2 со `status=active`. Строка названа условием («если
//      владелец включил в белый список»), потому что `property_create` — мутация: в `propose`
//      рутине доступен только `orbis_propose`, в `act` — ровно белый список
//      (`routineToolAllowed`, `tools/registry.ts`). `property_catalog` при этом открыт в обоих
//      режимах — он `read`, и признак `fullScopeOnly` на рутину не распространяется.
//
// Что НЕ входит в этот файл — то же, что и в v1/v2: режим прогона, его белый список, run_id
// и слот подставляются routineModeSection отдельной секцией системного канала.
//
// Блока продолжений у раннера нет и быть не должно (гард в тесте): собеседника у прогона нет.

