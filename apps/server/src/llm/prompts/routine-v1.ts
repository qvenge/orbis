// Системный слой раннера рутины (V1.5) — своя версионированная линейка, параллельная
// v1–v4 чат-ассистента. Правило то же: ИЗМЕНЕНИЕ текста = НОВЫЙ файл routine-vN +
// новая фикстура routine-v(N).fixture.txt; уже зафиксированная версия не правится.
//
// Почему отдельный промпт, а не SYSTEM_PROMPT_V4 (V1.5): у фонового прогона нет
// собеседника. Чат-промпт учит завершать ход «ответом пользователю» и добавлять чипы
// продолжений — в прогоне ответ читать некому, а маркер [[suggest:]] уехал бы в отчёт
// владельцу текстом (extractSuggestions раннер не зовёт). Взамен здесь названы вещи,
// которых в чате нет вовсе: терминальность orbis_propose, вопрос только чекпойнтом,
// белый список режима и запрет трогать рутины и назначения.
//
// Что НЕ входит в этот файл: режим конкретного прогона, его белый список, run_id и
// слот — они меняются от прогона к прогону и подставляются routineModeSection,
// отдельной секцией системного канала (иначе текст промпта перестал бы быть снимком).

