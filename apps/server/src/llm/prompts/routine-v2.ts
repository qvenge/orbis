// же, что у routine-v1: ИЗМЕНЕНИЕ текста = НОВЫЙ файл routine-vN + новая фикстура;
// routine-v1.ts и его фикстура с этого момента не правятся ни байтом — они снимок того,
// что читала модель до среза.
//
// ЗАЧЕМ ВЕРСИЯ. Срез построил механику, о которой промпт v1 не знает ничего, и хуже —
// три его утверждения стали ложью: «единственный способ спросить — orbis_checkpoint»,
// «он тоже терминален» и «если предлагать нечего — задай вопрос orbis_checkpoint».
// Промпт здесь не документация, а единственный включатель построенного: не назвав
// orbis_ask и отложку, срез работал бы вхолостую — модель продолжала бы закрывать прогон
// на первом же вопросе и читать «pending_confirmation» как отказ.
//
// ЧТО ИМЕННО ДОБАВЛЕНО (по одному предложению, чтобы следующая версия видела границу):
//   1. раздел «Как устроен этот прогон» — история несёт теперь и судьбы карточек, и их
//      формат объявлен дословно («спрашивал: … — ответ: …», «и ещё N решений»): усечение
//      без толкования модель прочитала бы как отмену остальных карточек;
//   2. раздел propose — выход из тупика начинается с нетерминального orbis_ask, а
//      orbis_checkpoint остаётся на случай «без ответа предложение не составить»;
//   3. раздел act — отложенное действие названо НЕ ошибкой, а запрещённое по объекту —
//      отказом, который повтором не чинится (эти два ответа сервера различаются только
//      текстом, и спутав их, модель либо бросит работу, либо будет долбиться в стену);
//   4. раздел «Вопрос владельцу» переписан под два инструмента и кап пачки.
//
// Что НЕ входит в этот файл — то же, что и в v1: режим прогона, его белый список, run_id
// и слот подставляются routineModeSection отдельной секцией системного канала.

