// apps/server/src/ai/suggestions.ts
// Продолжения разговора (решение D19): варианты СЛЕДУЮЩЕЙ реплики пользователя модель
// отдаёт маркером в конце своего ответа — второго вызова LLM ради чипов нет. Здесь —
// единственная точка разбора этого протокола; формат объявлен в системном промпте
// (блок «Продолжения разговора», prompts/v2.ts) — менять формат = менять И промпт.
//
// Деградация: маркера нет или он не совпал со строгой формой — продолжений у ответа
// просто нет, текст остаётся как есть. Ни угадывания «почти маркера», ни мусора в ленте.

/** Сколько продолжений максимум доезжает до клиента (промпт просит 2–4). */
export const SUGGESTIONS_MAX = 4;

/**
 * Потолок длины продолжения в СИМВОЛАХ (не UTF-16-юнитах). Длиннее — элемент
 * отбрасывается целиком: усечение посреди слова дало бы бессмысленный чип, а
 * промпт и так просит короткие формулировки.
 */
export const SUGGESTION_MAX_LEN = 60;

/**
 * Строгая форма маркера: отдельная ПОСЛЕДНЯЯ строка ответа вида
 * `[[suggest: что по бюджету? | поставить срок]]`. Требования формы:
 * - маркер завершает ответ (`\s*$`) — иначе это проза, а не протокол;
 * - перед ним начало текста или пробельный отступ (жадный `\s+` заодно снимает
 *   ведущие переводы строк, чтобы после вырезания не осталось хвоста пустых строк);
 * - содержимое непустое и однострочное — `[[suggest:]]` формой НЕ является.
 */
export const SUGGEST_MARKER_RE = /(?:^|\s+)\[\[suggest:([^\]\n]+)\]\]\s*$/;

export interface ExtractedSuggestions {
  /** Текст ответа без служебной строки (может стать пустым — так и оставляем). */
  text: string;
  /** Разобранные продолжения; пустой список — чипов у ответа нет. */
  suggestions: string[];
}

/**
 * Отделяет продолжения от прозы модели. Вызывать НУЖНО до любых дописок к тексту
 * (пометки обрыва/лимита шагов): после склейки маркер перестаёт быть последней
 * строкой и утёк бы в ленту как обычный текст.
 */
export function extractSuggestions(raw: string): ExtractedSuggestions {
  const match = SUGGEST_MARKER_RE.exec(raw);
  const body = match?.[1];
  if (match === null || body === undefined) return { text: raw, suggestions: [] };

  const suggestions = body
    .split('|')
    .map((part) => part.trim())
    .filter((part) => part.length > 0 && [...part].length <= SUGGESTION_MAX_LEN)
    .slice(0, SUGGESTIONS_MAX);

  return { text: raw.slice(0, match.index), suggestions };
}
