export const ROUTINE_TOOLS_PROPERTY = 'orbis/allowed_tools';
/**
 * Адрес СТАДИИ — рядом с адресами доверенности, но НАМЕРЕННО ВНЕ `AUTONOMY_PROPERTIES`.
 *
 * Стадия — не доверенность, а ВЫКЛЮЧАТЕЛЬ: она не говорит, что рутине позволено, она говорит,
 * работает ли рутина вообще (третье условие отбора `activeRoutines`). Попади она в список
 * доверенности — гейт формы стал бы требовать карточку на любую постановку на паузу, то есть
 * на СУЖЕНИЕ прав, а замок §7.10 стоит не за этим. Оба направления и их статус разобраны в
 * докблоке `grantsRoutineAutonomy` ниже; дом у адреса один — здесь, рядом с остальными
 * адресами рутины, и он пиннится к реестру тем же тестом.
 *
 * ЧИТАТЕЛЕЙ ЧЕТЫРЕ, и первый из них важнее прочих:
 *  1. `agent-loop/queries.ts` — САМ ОТБОР `activeRoutines`, ради которого замок и стоит. Если
 *     он разъедется с `liveRoutine` (`tools/dispatch.ts`), замок начнёт защищать не тот отбор,
 *     и заметить это будет нечем;
 *  2. `tools/dispatch.ts` — проба состояния (`liveRoutine`, `revivedByPatch`);
 *  3. `routers/routine.ts` — показывать ли «следующее срабатывание» (у паузы его нет);
 *  4. `routines/lifecycle.ts` — постановка рутины на паузу при сбое, вместе с предусловием.
 * Перечень пересчитан грепом по литералу и по константе; пятого ЧИТАТЕЛЯ нет. Литералом адрес
 * остаётся ровно в одном месте — ключ интерфейса `RoutineProps` (`agent-loop/queries.ts`), — и
 * это не читатель, а ОБЪЯВЛЕНИЕ ТИПА: вычисляемые ключи там законны, но три ключа из пяти
 * остались бы литералами, а гарантию даёт обратное направление — константа проверяется ОБ этот
 * интерфейс, и её расхождение с адресом не компилируется.
 */
