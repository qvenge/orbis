import { batchExecuteInput } from '@orbis/shared';
import type { ActionRecord, ActorKind } from '../executor/types';
import { REGISTRY_TOOL_NAMES } from '../tools/registry-tools';

/** Уровни подтверждения §7.10 (семантика каждого — таблица PRD 01 §7.10). */
export type ConfirmationLevel = 'execute' | 'preview' | 'explicit-confirmation' | 'forbidden';

/**
 * ЧТО ВЫЗОВ ПЕРЕНАСТРАИВАЕТ В САМОЙ СИСТЕМЕ (§С2-1) — вход §7.10 «перенастраивает
 * поверхность или права». Это не «какой тул позвали», а КАКОЙ ОБЪЕКТ вызов меняет: у
 * реестра одно и то же имя тула трогает то свою строку владельца, то системную.
 *
 * - `none` — вызов реестра не трогает вовсе (весь остальной корпус тулов);
 * - `own-property` — СВОЯ строка владельца заводится или получает новую подпись/место
 *   показа (§С2-1 ряд 1): «показать» — карточкой, как всякое AI-действие;
 * - `behavior-delta` — меняется ПОВЕДЕНИЕ системы: статус свойства (предложенное входит в
 *   промпт, активное закрывается), слияние двух свойств (значения переезжают, сохранённые
 *   запросы переписываются), дельта аспекта (скрытия, состав, наборы вариантов). §С2-1 ряд
 *   2: «обсудить» — для ЛЮБОГО актора, у рутин — отложенная единица пачки;
 * - `system-object` — объект НЕ ПРИНАДЛЕЖИТ владельцу: встроенное свойство, встроенный
 *   аспект (а с частью Б — его `implements`, роли `created_by: system`, определения чужих
 *   модулей). §С2-1 ряд 3: фону — запрет ПО ОБЪЕКТУ, который не откладывается никогда.
 */
export type Reconfigures = 'none' | 'own-property' | 'behavior-delta' | 'system-object';

/** Типизированные факты tool-call — входы классификации §7.10. */
export interface ToolCallFacts {
  tool: string;
  kind: 'read' | 'mutate';
  known: boolean; // тул есть в реестре (§9.2)
  actorKind: ActorKind;
  explicitCommand: boolean; // §7.10 «явность намерения»; в 1b всегда false (ToolCallCtx)
  archives: boolean; // мутация архивации: archived: true в input (мягкое удаление)
  isBatch: boolean;
  batchSize?: number;
  /**
   * Выдача автономии рутине (V1.10): создание/attach рутины с `mode: 'act'` либо правка
   * её доверенности (`mode`/`allowed_tools`). Право писать в граф без спроса выдаёт только
   * владелец — модели и внешнему агенту оно достаётся через карточку подтверждения.
   */
  grantsAutonomy: boolean;
  /**
   * §С2-1: перенастраивает ли вызов саму систему и КАКОЙ объект при этом трогает.
   * Считается по имени тула и адресу объекта — `reconfiguresOf` ниже.
   */
  reconfigures: Reconfigures;
}

/**
 * Классификатор §7.10 — таблица правил MVP, первое совпадение сверху (порядок значим):
 *
 * | Условие                             | Уровень                | Обоснование §7.10 |
 * |-------------------------------------|------------------------|-------------------|
 * | !known                              | forbidden              | fail-closed: незнакомый вызов не исполняется |
 * | kind === 'read'                     | execute                | чтение без внешних эффектов |
 * | archives && !explicitCommand        | explicit-confirmation  | архивация = мягкое удаление; инициатива модели/агента без прямой команды — чувствительно |
 * | 4a: behavior-delta ∨ system-object   | explicit-confirmation  | §С2-1: перенастройка поведения и системных объектов — «обсудить», для ЛЮБОГО актора |
 * | isBatch && batchSize > 10           | explicit-confirmation  | масштаб приближается к bulk |
 * | grantsAutonomy && !owner            | explicit-confirmation  | V1.10: право рутины писать в граф выдаёт только владелец |
 * | 4b: own-property && !owner          | preview                | §С2-1: своя строка реестра — «показать» карточкой; владелец делает это сам |
 * | isBatch                             | preview                | bounded-масштаб: исполнить + информационный diff |
 * | иначе (одиночная мутация)           | execute                | single, обратимо (inverse в журнале §7.8) |
 *
 * actorKind — вход политики §7.10; MVP-таблица ветвится по нему ровно в двух рядах —
 * автономии рутины (V1.10) и своей строки реестра (§С2-1): владельцу подтверждать нечего, он
 * и есть тот, у кого спрашивают. Прочие ряды по актору не ветвятся: ряд archives адресует
 * инициативу модели/агента, ряд 4a §С2-1 требует «ни для какого актора молча», а owner-актор
 * до классификатора обычно не доходит (прямые действия владельца идут UI-роутерами мимо
 * dispatch — `routers/registry.ts` зовёт `execute` напрямую).
 *
 * Ряд автономии стоит ВЫШЕ «isBatch → preview» намеренно: preview исполняет действие и лишь
 * показывает diff, то есть batch из двух операций провёз бы выдачу прав молча.
 *
 * ПОЧЕМУ НОВЫЕ РЯДЫ РАЗВЕДЕНЫ, А НЕ СТОЯТ ПАРОЙ ПОД РЯДОМ 3. Оба они новые, но работают в
 * РАЗНЫЕ стороны, и место у каждого своё:
 *  - 4a ПОВЫШАЕТ уровень, поэтому стоит как можно выше — сразу под рядом 3;
 *  - 4b ПОНИЖАЕТ его до `preview`, поэтому стоит НИЖЕ ВСЕХ рядов, дающих
 *    `explicit-confirmation`. Стой он рядом с 4a, пачка из 11 операций с одним
 *    `property_create` внутри получила бы `preview` вместо подтверждения по масштабу, а
 *    пачка «завести своё свойство + выдать автономию рутине» провезла бы выдачу прав молча:
 *    первое совпадение сверху погасило бы оба замка. Это не гипотеза — `property_create`
 *    доезжает до `batch_execute` (`MUTATION_ENVELOPES` включает конверты реестра), и обе
 *    подмены пиннятся тестами «ряд 4b не гасит…».
 */
export function classifyToolCall(facts: ToolCallFacts): ConfirmationLevel {
  if (!facts.known) return 'forbidden';
  if (facts.kind === 'read') return 'execute';
  if (facts.archives && !facts.explicitCommand) return 'explicit-confirmation';
  // 4a (§С2-1 ряды 2 и 3): «молчаливых мутаций реестра не существует ни для какого актора».
  // Запрет по объекту для ФОНА — не здесь: классификатор по актору и источнику сознательно
  // не ветвится, и `system-object` он поднимает до подтверждения, а `tools/dispatch.ts`
  // (`routineDeferForbidden`) превращает это подтверждение в отказ для прогона.
  if (facts.reconfigures === 'behavior-delta' || facts.reconfigures === 'system-object') {
    return 'explicit-confirmation';
  }
  if (facts.isBatch && facts.batchSize !== undefined && facts.batchSize > 10) {
    return 'explicit-confirmation';
  }
  if (facts.grantsAutonomy && facts.actorKind !== 'owner') return 'explicit-confirmation';
  // 4b (§С2-1 ряд 1): своя строка владельца, заведённая или переподписанная от имени AI.
  if (facts.reconfigures === 'own-property' && facts.actorKind !== 'owner') return 'preview';
  if (facts.isBatch) return 'preview';
  return 'execute';
}

/**
 * Извлечение фактов формы вызова из (def, input). Контракт (fix round Task 5; §7.10
 * дословно: уровень получает tool-call ПОСЛЕ структурной валидации input'а): dispatch
 * передаёт сюда уже envelope-ВАЛИДИРОВАННЫЙ input (validateMutationEnvelope /
 * validateBatchOperations) — классификация невалидированного payload'а в dispatch не
 * происходит. Ветки на сырой input (не-объект → archives false, невалидный
 * batch-envelope → fallback «не batch») сохранены как защитные и покрыты юнитами:
 * функция не падает на мусоре, а невалидный вызов отклоняет валидация вызывающего.
 * Акторные факты (actorKind, explicitCommand) добавляет вызывающий из ToolCallCtx;
 * known: true — сюда доходит только найденный реестром def, ряд «!known» dispatch
 * строит сам по результату резолва.
 */
export function factsFromToolCall(
  def: { name: string; kind: 'read' | 'mutate' },
  input: unknown,
): Omit<ToolCallFacts, 'actorKind' | 'explicitCommand'> {
  const base = { tool: def.name, kind: def.kind, known: true as const };
  if (def.name === 'batch_execute') {
    const parsed = batchExecuteInput.safeParse(input);
    if (parsed.success) {
      return {
        ...base,
        archives: parsed.data.operations.some((op) => op.input.archived === true),
        isBatch: true,
        batchSize: parsed.data.operations.length,
        // ЛЮБАЯ операция batch, выдающая автономию, поднимает уровень всего вызова:
        // batch исполняется «всё или ничего», подтверждать его тоже приходится целиком
        grantsAutonomy: parsed.data.operations.some((op) =>
          grantsRoutineAutonomy(op.tool, op.input),
        ),
        // Тем же правилом, что и автономия, и по той же причине: batch исполняется «всё или
        // ничего», поэтому у пачки берётся САМЫЙ ТЯЖЁЛЫЙ ответ её операций. Реестровые тулы
        // внутрь batch доезжают (их конверты есть в `MUTATION_ENVELOPES` диспатча), и без
        // этой свёртки `property_merge`, завёрнутый в пачку из двух операций, получал бы
        // `preview` — то есть исполнялся бы сразу.
        reconfigures: heaviestReconfigures(
          parsed.data.operations.map((op) => reconfiguresOf(op.tool, op.input)),
        ),
      };
    }
    return {
      ...base,
      archives: false,
      isBatch: false,
      grantsAutonomy: false,
      // Невалидный конверт batch: операций не видно, значит и ответить про них нечем.
      // `none` здесь безопасно — такой вызов отвергает envelope-валидация вызывающего ещё
      // до классификации (см. докблок выше), а до исполнения он не доходит вовсе.
      reconfigures: 'none',
    };
  }
  return {
    ...base,
    reconfigures: reconfiguresOf(def.name, input),
    // Архивация — только entity_update (§9.2: archived есть лишь в его envelope);
    // archived в чужом strict-envelope — невалидный input, честный отказ
    // envelope-валидации dispatch (fix round) ещё до классификации
    archives: def.name === 'entity_update' && isRecord(input) && input.archived === true,
    isBatch: false,
    grantsAutonomy: grantsRoutineAutonomy(def.name, input),
  };
}

/**
 * Порядок тяжести ответов §С2-1 — им сворачивается пачка (batch исполняется целиком).
 * Числа значимы только относительно друг друга: «системный объект тяжелее перенастройки
 * поведения, та тяжелее правки своей строки, та тяжелее ничего».
 */
const RECONFIGURES_WEIGHT: Record<Reconfigures, number> = {
  none: 0,
  'own-property': 1,
  'behavior-delta': 2,
  'system-object': 3,
};

function heaviestReconfigures(values: readonly Reconfigures[]): Reconfigures {
  let out: Reconfigures = 'none';
  for (const value of values) {
    if (RECONFIGURES_WEIGHT[value] > RECONFIGURES_WEIGHT[out]) out = value;
  }
  return out;
}

/**
 * СВОЙ ЛИ ЭТО АДРЕС РЕЕСТРА — одна проба на все три вопроса §С2-1 (свойство у
 * `property_update`, оба конца у `property_merge`, аспект у дельты).
 *
 * Своя строка владельца адресуется РОВНО ДВУМЯ способами, и оба гарантированы, а не приняты
 * на веру:
 *  - `id` собственной строки — uuid (`registry/ops.ts`, `createProperty`: «id — uuid (Р3):
 *    читаемая строка есть только у встроенных»);
 *  - `key` в namespace автора — `user/…` (§А2-1). Гейт `KEY_NAMESPACE` (там же) не даёт
 *    завести свою строку ни в каком другом namespace, и причина у него ровно эта: иначе
 *    своя строка молча подменила бы системную с тем же ключом.
 * Всё остальное — `orbis/…` встроенных и любой будущий `<app>/…` (§А3-3) — адресует ЧУЖУЮ
 * строку: системную либо принадлежащую модулю/приложению. Ответ fail-closed: незнакомая
 * форма адреса считается чужой, и вызов поднимается до подтверждения, а не проваливается в
 * `execute`.
 *
 * ПОЧЕМУ ПО АДРЕСУ, А НЕ ПО СНИМКУ РЕЕСТРА. Классификатор §7.10 чист по построению —
 * типизированные факты вызова, без БД (см. докблок `grantsRoutineAutonomy`); спросить у базы
 * `owner_id` строки он не может. Namespace даёт тот же ответ БЕЗ чтения, и даёт его строже:
 * у несуществующего `orbis/выдумка` он честно скажет «чужой», тогда как снимок сказал бы
 * «строки нет» и вопрос об уровне остался бы без ответа. Проверку существования и
 * принадлежности делает исполнение — `BUILTIN_IMMUTABLE`/`MERGE_BUILTIN`/`NOT_FOUND`
 * (`registry/ops.ts`); этот гейт — их ЗЕРКАЛО на уровне подтверждения, ровно как объектный
 * пре-чек рутины зеркалит стадию 4 исполнителя.
 *
 * ПРО ВСТРОЕННЫЕ АСПЕКТЫ ЭТО ЗНАЧИТ БУКВАЛЬНО СЛЕДУЮЩЕЕ: дельта поверх любого из тринадцати
 * встроенных аспектов — `system-object`. Не потому, что дельта незаконна (она и есть штатный
 * способ настроить систему под себя, §А3-2), а потому, что ФОНУ она не адресована: «тихо
 * перенастроить, что видит владелец» — прямая анти-цель 3 (§С2-3). Владельцу и модели в чате
 * ряд 4a даёт то же `explicit-confirmation`, что и любой другой перенастройке поведения, —
 * разница видна только фону. Сюда же попадают три объекта машинерии делегирования
 * (`orbis/routine`, `orbis/agent-run`, `orbis/assignment`): реконфигурация их определения —
 * тот же переход, что запрещён рутине над их ЗАПИСЯМИ (`ROUTINE_UNTOUCHABLE_OBJECTS`),
 * только другой дверью, и отдельного списка для него заводить не пришлось.
 *
 * Дельта поверх СВОЕГО аспекта владельца (`user/…`, такие строки реестр несёт — см.
 * `seedCustomAspect`, `executor/props.test.ts`) остаётся `behavior-delta`: объект его, и
 * рутина вправе предложить правку отложенной единицей. Тула, заводящего свой аспект, срез А
 * не даёт (§С3 отдаёт его владельцу/AI позже) — правило написано по АДРЕСУ и потому
 * встретит такой аспект готовым, а не отдельной веткой.
 */
function ownRegistryAddress(value: unknown): boolean {
  if (typeof value !== 'string') return false;
  return UUID_RE.test(value) || value.startsWith('user/');
}

const UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

/**
 * ЧТО ОДНА ОПЕРАЦИЯ ПЕРЕНАСТРАИВАЕТ В СИСТЕМЕ (§С2-1) — по имени тула и АДРЕСУ ОБЪЕКТА.
 *
 * ПЕРЕЧЕНЬ СОБРАН ПО ПЕРЕХОДАМ ЗАЩИЩАЕМОГО СОСТОЯНИЯ, А НЕ ПО ФОРМАМ ВЫЗОВА — это вывод из
 * десяти фикс-раундов Задачи 12, где замок автономии обходили девятью формами подряд.
 * Защищаемое состояние здесь — «что владелец видит и что система делает»: словарь свойств,
 * их подписи и области показа, эффективные определения аспектов. Переходов, доступных пяти
 * тулам реестра среза А, СЕМЬ, и у каждого свой ответ:
 *
 *  1. родилась новая своя строка (`property_create`, active либо proposed) → `own-property`;
 *  2. у своей строки сменились подпись/смысл/область показа/место в порядке
 *     (`property_update` без `status`) → `own-property`;
 *  3. своя строка сменила СТАТУС (`property_update` со `status`) → `behavior-delta`:
 *     `proposed → active` вводит свойство в промпт и на поверхности, `active → deprecated`
 *     закрывает запись новых значений, а отклонение неиспользованного предложения СТИРАЕТ
 *     строку совсем (`updateProperty`, ветка DELETE);
 *  4. два своих свойства слились в одно (`property_merge`): значения записей переехали,
 *     сохранённые запросы и тела переписаны, у поглощённого встал `merged_into` →
 *     `behavior-delta`;
 *  5. у аспекта появилась или сменилась дельта (`aspect_delta_set`): подпись, иконка, состав
 *     свойств, скрытия, ослабления обязательности, наборы вариантов select;
 *  6. дельта аспекта снята (`aspect_delta_remove`) — эффективное определение вернулось к
 *     системному, а всё, что владелец настроил, исчезло;
 *  7. любой из шести переходов адресован ЧУЖОМУ объекту (встроенное свойство, встроенный
 *     аспект) → `system-object`, и это перекрывает ответ по переходу.
 * Восьмого перехода у этих пяти тулов нет: `registry_version` двигает каждый из них, и
 * отдельным переходом она не считается — это следствие, а не жест.
 *
 * ЧЕГО ЭТОТ ПЕРЕЧЕНЬ НЕ ЗАКРЫВАЕТ, И ЭТО НАЗВАНО, А НЕ ЗАБЫТО: `undo_last`. Владелец
 * подтверждает карточкой слияние свойств, оно ложится в журнал одним action'ом — и следующий
 * `undo_last` ОТ МОДЕЛИ применяет его inverse (`property_merge_undo`), возвращая словарь
 * назад без всякой карточки. Это ТОТ ЖЕ известный путь, что уже описан в докблоке
 * `grantsRoutineAutonomy` ниже (воспроизведён живьём в фикс-раунде 6 Задачи 12 на
 * доверенности рутины): `undoLast` берёт последнее неотменённое действие журнала владельца,
 * не различая, кто его совершил. Лечение лежит ВНЕ этого замка — в ответе на вопрос, какие
 * действия вообще отменяемы моделью, — и разбор ушёл владельцу. Фону путь закрыт:
 * `undo_last` в `ROUTINE_CLOSED_TOOLS` (`tools/registry.ts`).
 */
export function reconfiguresOf(tool: string, input: unknown): Reconfigures {
  if (!REGISTRY_TOOL_NAMES.has(tool)) return 'none';
  // Форма проверяется защитно: сюда доезжает уже envelope-валидированный payload (тот же
  // довод, что у `grantsRoutineAutonomy`). Мусор — самый тяжёлый ответ, а не самый лёгкий.
  if (!isRecord(input)) return 'system-object';
  switch (tool) {
    case 'property_create':
      // Строка ещё не существует, чужой её сделать нельзя: `KEY_NAMESPACE` не пускает
      // явный key за пределы `user/`, а собранный из подписи и подавно там (§А2-1).
      return 'own-property';
    case 'property_update':
      if (!ownRegistryAddress(input.id)) return 'system-object';
      return 'status' in input ? 'behavior-delta' : 'own-property';
    case 'property_merge':
      // ОБА конца, а не только источник: слияние пишет и в цель тоже (значения переезжают
      // в неё), и «встроенное свойство целью» — такая же перенастройка чужой строки. Та же
      // мерка, что у гейта хранилища `MERGE_STORAGE` (`registry/ops.ts`), где проверяются
      // тоже оба.
      return ownRegistryAddress(input.source) && ownRegistryAddress(input.into)
        ? 'behavior-delta'
        : 'system-object';
    case 'aspect_delta_set':
    case 'aspect_delta_remove':
      return ownRegistryAddress(input.aspect) ? 'behavior-delta' : 'system-object';
  }
  // Недостижимо: имена закрыты `REGISTRY_TOOL_NAMES`, и switch выше перечисляет все пять.
  // Fail-closed на случай шестого тула реестра, заведённого без правки этой функции.
  return 'system-object';
}

/**
 * Адреса ДОВЕРЕННОСТИ рутины (§А9-1) — ОДНО объявление на систему.
 *
 * Читателей ШЕСТЬ, и вопросы у них разные:
 *  1. гейт §7.10 ниже — поднимать ли уровень до `explicit-confirmation`;
 *  2. сводка карточки (`tools/dispatch.ts`, `autonomySummary` и `AUTONOMY_LABEL`) — что
 *     назвать владельцу;
 *  3. проба носителя (`autonomyChangedByCarrier`, там же) — что вызов отнимает или выдаёт;
 *  4. гейт правки инструкции (`actRoutineInstructionTargets`, там же) — act-рутина ли цель;
 *  5. `routines/runner.ts` — режим прогона и белый список реестра тулов;
 *  6. `routines/context.ts` — секция режима в системном слое.
 * Первые четыре решают, что показать владельцу, последние два — что рутине ПОЗВОЛЕНО; пока
 * адреса стояли врозь, карточка могла рассказывать не о том, что подняло уровень. Это класс
 * обоих Critical ветки («множество должно быть ОДНИМ у всех потребителей»). Перечень
 * пересчитан грепом по обеим константам и `AUTONOMY_PROPERTIES`; седьмого читателя нет.
 *
 * ОДНОГО МНОЖЕСТВА МАЛО — читать его все шестеро обязаны ОДИНАКОВО ПОЛНО. Фикс-раунд 2 нашёл
 * ровно этот недобор: адреса уже были общими, а сводка ходила только в `props`, и вызов
 * `{unset:['orbis/allowed_tools']}` поднимал уровень с ПУСТОЙ карточкой. Правя одного
 * читателя, проверь остальных — унификация имён сама по себе ничего не гарантирует. Тот же
 * недобор в перечне: фикс-раунд 4 насчитал ПЯТЬ, пропустив четвёртого, — а ценен докблок
 * именно инструкцией «проверь остальных», и перечень с пропуском её подводит.
 *
 * Двое из шести живут в `routines/*` и читают доверенность из типизированного `RoutineProps`
 * — там расхождение константы с адресом не компилируется. Литеральные читатели, до которых
 * константа дойти не может (реестр свойств в `@orbis/shared`), связаны с ней пином в
 * `confirmation.test.ts` («адреса доверенности ≡ реестр»).
 *
 * Режим отдельной константой рядом со списком: у НАБОРА, кладущегося целиком, значимы оба, но
 * по-разному (`autonomyArmed` ниже), а у ПАТЧА значим сам факт правки любого из двух.
 */
