import { Component, type ReactNode } from 'react';
import { Button } from '../ui/Button';
import { ScreenHeader } from './ScreenHeader';

type Props = {
  children: ReactNode;
  /**
   * Идентификатор экрана под границей. Смена значения снимает прошлый провал.
   * Обязателен намеренно: без него граница, поймавшая ошибку один раз, держит свой кадр
   * ВЕЧНО — включая вкладки, чьи экраны грузятся статически и ни в чём не виноваты
   * (state класса переживает любую смену children). Необязательный проп оставлял бы тип,
   * при котором это запирание возвращается молча.
   *
   * Прокидывать сюда `key` нельзя: он ремонтировал бы и само поддерево, а внутри одного
   * kind'а (DetailScreen со сменой entityId) это стоило бы состояния экрана.
   */
  resetKey: string;
};
type State = { failed: boolean; shownFor: string | undefined };

/**
 * ЕДИНСТВЕННАЯ граница ошибок в приложении — до неё их не было вовсе, и любая ошибка
 * рендера уносила весь React-корень в белый экран. Стоит вокруг всего содержимого <main>,
 * то есть ловит теперь рендер ЛЮБОГО экрана, а не только ленивого: Chat, Browser, Agenda,
 * Detail, Settings, Memory тоже под ней. Поэтому текст кадра нейтрален («Не удалось открыть
 * экран»): «не удалось загрузить» подписывало бы упавший рендер Чата чужой причиной.
 *
 * Поводом завестись был отказ, который ввела ленивая загрузка: чанк экрана не приехал
 * (устаревшая вкладка после деплоя, пропавшая сеть). Первый такой провал chunk-reload.ts
 * лечит перезагрузкой; сюда доезжает второй.
 *
 * ВАЖНО про восстановление: `resetKey` разблокирует ДРУГИЕ экраны, но не чинит упавший.
 * React.lazy кэширует отказ загрузчика навсегда — `lazyInitializer` заходит в блок загрузки
 * только при `_status === -1` (react/cjs/react.development.js:461), при отказе ставит
 * `_status = 2` (:478-486) и дальше на КАЖДОМ рендере синхронно перебрасывает сохранённую
 * ошибку (:513). Загрузчик второй раз не зовётся вовсе. То есть «сеть отвалилась → чанк не
 * приехал → сеть вернулась» само не рассасывается: сколько бы пользователь ни ходил по
 * вкладкам, этот экран будет отдавать тот же кадр. Единственное лечение — перезагрузка
 * страницы, она же кнопка ниже. Ретрай-обёртки над lazy у нас сознательно нет: это
 * отдельная способность и отдельное решение.
 *
 * Кнопка, а не автоматический reload: цикл перезагрузок при настоящей потере сети хуже
 * одного честного экрана. Форма кадра — как у соседа с той же ролью
 * (OnboardingGate.tsx:38-56): role="alert", text-danger, кнопка variant="outline".
 * Вертикальной центровки, в отличие от соседа, нет: шапка забирает свою высоту, и кадр
 * висит под ней — так же, как содержимое любого другого экрана.
 */
export class ChunkErrorBoundary extends Component<Props, State> {
  state: State = { failed: false, shownFor: undefined };

  static getDerivedStateFromError(): Partial<State> {
    return { failed: true };
  }

  // Провал помечен экраном, на котором случился (`shownFor` записывается ДО ошибки,
  // на обычном рендере). Пока экран тот же — кадр держится; сменился — снимаем.
  static getDerivedStateFromProps(props: Props, state: State): State | null {
    if (props.resetKey === state.shownFor) return null;
    return { failed: false, shownFor: props.resetKey };
  }

  render() {
    if (!this.state.failed) return this.props.children;
    return (
      <>
        {/* Шапка — по той же причине, по какой она есть у ScreenFallback (там же и разбор):
            без неё «Назад» пропадает, и в standalone-PWA (pwa/manifest.ts:6), где системной
            кнопки назад нет, пользователь запирается на кадре ошибки — возврат на тот же
            экран снова даёт его же. Титул «…» вместо угаданного: какой экран не открылся,
            граница не знает. */}
        <ScreenHeader title="…" />
        <div role="alert" className="flex flex-col items-center gap-3 p-6 text-sm text-danger">
          <span>Не удалось открыть экран</span>
          <Button variant="outline" data-testid="chunk-reload" onClick={() => location.reload()}>
            Обновить
          </Button>
        </div>
      </>
    );
  }
}
