import { createContext } from 'react';

/**
 * В какой рамке нарисован элемент хоста (спека 1б §6.2, §6.3): `true` — внутри рамки десктопа
 * (`DesktopFrame`: ⌂ в рейке, навигация в сайдбаре, 💬 — боковой чат), `false` — рамка телефона.
 *
 * Контекст, а не ширина экрана: рамку выбирает `AppShell`, и форма элементов обязана следовать за
 * РАМКОЙ. Пока чанк рамки десктопа едет или не приехал, на ширине десктопа стоит рамка телефона, и
 * её элементы хоста — телефонные (⌂ в строке присутствия, 💬 — экран хоста), иначе рамка осталась
 * бы без ⌂ и с 💬, открывающим чат, которого нет (§6.6: элементы хоста — всегда).
 */
export const DesktopFrameContext = createContext(false);
