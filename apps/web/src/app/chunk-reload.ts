/**
 * Провал загрузки ленивого чанка ЧАЩЕ ВСЕГО означает одно: вкладка открыта на старом
 * index.html, а деплой уже сменил имена чанков (каждый деплой — новый контейнер с чистым
 * dist, старые файлы исчезают). Лечится перезагрузкой: свежий index.html знает новые имена.
 * Перезагрузка здесь ещё и единственное лечение в принципе — провал import() оседает
 * в module map документа и в кэше React.lazy до конца жизни страницы (см. п. 2 бэклога и
 * докблок ChunkErrorBoundary).
 *
 * Vite шлёт на window событие 'vite:preloadError', когда динамический import() не удался.
 *
 * НО «чаще всего» — не «всегда», и цена ошибки несимметрична. Событие приходит на ЛЮБОЙ
 * отказ import(): мёртвая сеть, спящий инстанс (`plan: free` в render.yaml — Render усыпляет
 * его и будит небыстро), 502 в момент выкатки. Перезагрузка в этих случаях помочь не может
 * НИЧЕМ, а забирает всё: вкладка уходит на страницу ошибки браузера, приложение исчезает
 * целиком вместе с недописанным текстом в композере. Живой смоук это воспроизвёл на
 * остановленном сервере.
 *
 * Поэтому перед перезагрузкой спрашиваем сервер, жив ли он (см. `serverIsUp`). Ответил —
 * перезагружаемся, свежему index.html есть откуда приехать. Не ответил — не перезагружаемся
 * и НЕ тратим единственную попытку: пользователь увидит кадр ChunkErrorBoundary с кнопкой
 * «Обновить» и нажмёт её сам, когда сервер вернётся.
 *
 * `navigator.onLine` для этой развилки не годится и был отвергнут по улике: при спящем и
 * при перезапускающемся сервере он остаётся `true`, то есть молчит ровно в самом частом
 * случае.
 *
 * Событие мы намеренно НЕ отменяем (`preventDefault`). Решение асинхронно, а vite читает
 * `defaultPrevented` синхронно сразу после `dispatchEvent`, так что отменить «на всякий
 * случай» значило бы отменять и в той ветке, где мы не перезагружаемся: vite тогда гасит
 * ошибку, `import()` резолвится в `undefined`, и React бросает из `lazyInitializer`
 * бессмысленное «Cannot read properties of undefined (reading 'default')» вместо настоящего
 * «Failed to fetch dynamically imported module». Ценой одного uncaught в консоли сохраняем
 * честную ошибку — и в консоли, и в том, что доедет до границы.
 *
 * Перезаход РОВНО ОДИН на сессию вкладки. Второй провал уже не про устаревший index.html —
 * это сеть или сервер, и повторная перезагрузка превратилась бы в цикл. Флаг живёт в
 * sessionStorage (переживает reload, умирает с вкладкой) и намеренно НЕ снимается: второй
 * деплой за одну сессию вкладки — редкость, и там честнее показать экран с кнопкой
 * (ChunkErrorBoundary), чем перезагружать пользователя молча ещё раз.
 *
 * ОСТОРОЖНО с фоновой догрузкой чанков (её здесь заводили и убрали, разбор —
 * docs/superpowers/reviews/2026-08-10-lazy-split-backlog.md:17). Событие приходит на ЛЮБОЙ
 * провалившийся динамический import, и отличить свой от пользовательского эта функция не
 * может: перезаход по чужому провалу забирает страницу у человека, который ничего не нажимал,
 * а глушить событие «пока в полёте фоновая задача» нельзя — на входе по ссылке /entity/<id>
 * провал ПОЛЬЗОВАТЕЛЯ приходит позже старта догрузки и был бы съеден вместе с ним. Вдобавок
 * провал import() навсегда оседает в module map документа, так что моргнувшая сеть ломала бы
 * экран до конца сессии.
 *
 * Греть чанки можно только тем, что в module map не заходит и это событие не шлёт
 * (link rel=modulepreload), НО СЕГОДНЯ ЭТОТ ПУТЬ ЗАКРЫТ: имя чанка взять неоткуда. Оно
 * известно только сборке — build.manifest выключен (каталога dist/.vite/ нет), а
 * __vite__mapDeps в собранном входном чанке остаётся приватным const модульной области и в
 * список export{…} не попадает. Открыть путь можно лишь правкой vite.config.ts
 * (build.manifest: true) или своим плагином сборки; ?url не подходит по существу — он эмитит
 * отдельный ассет со своим хешем, не связанный с чанком от import(). Ближайшая рабочая
 * альтернатива — не фон, а прогрев внутри жеста (onPointerDown на строке, пушащей экран):
 * он пользовательский по построению, и эта функция обрабатывает его провал верно.
 * Подробности и условия возврата — п. 1 и п. 2 того же бэклога.
 */
const RELOADED_FLAG = 'orbis:chunk-reloaded';

// Потолок ожидания ответа /health. Живой инстанс отвечает за десятки миллисекунд, так что
// на путь «перезагружаемся» это время не влияет вовсе. Значение ограничивает только ветку
// «сервер молчит», и там пользователь ничего не ждёт: кадр ChunkErrorBoundary уже на экране
// (событие мы не отменяли, ошибка дошла до React своим ходом). Две секунды — чтобы отложенная
// перезагрузка не прилетела человеку, который уже прочитал кадр и тянется к кнопке.
const PROBE_TIMEOUT_MS = 2000;

/**
 * Жив ли сервер, которому предстоит отдать свежий index.html и новые чанки.
 * `/health` — его собственная проверка (`healthCheckPath` в render.yaml,
 * `apps/server/src/app.ts:97`), и статику раздаёт ТОТ ЖЕ origin (один web-сервис,
 * см. шапку render.yaml). То есть ответ на неё — прямое свидетельство, что перезагрузке
 * есть куда приехать, а не догадка о состоянии сети.
 *
 * `cache: 'no-store'` — ответ из кэша означал бы «сервер был жив когда-то».
 * Любой отказ (сеть, таймаут, не-2xx, отсутствие AbortSignal.timeout в старом браузере) —
 * это «не знаем, что сервер жив», и трактуется как «не перезагружаться»: молчание должно
 * склонять к бездействию, потому что ошибочная перезагрузка забирает приложение целиком.
 */
async function serverIsUp(): Promise<boolean> {
  try {
    const res = await fetch('/health', {
      cache: 'no-store',
      signal: AbortSignal.timeout(PROBE_TIMEOUT_MS),
    });
    return res.ok;
  } catch {
    return false;
  }
}

/**
 * `true` — попытка уже потрачена, `false` — ещё нет, `null` — хранилище недоступно.
 * Читать sessionStorage без try/catch нельзя: при заблокированном хранилище (сторонний
 * контекст, «блокировать все cookies» в Safari) `getItem` бросает SecurityError прямо
 * из слушателя события. Конвенция проекта та же — см. пре-пейнт-скрипт в index.html.
 * `null` трактуется как «не перезагружаться»: без флага гарантии «ровно один раз» нет,
 * а перезагрузка без такой гарантии — это цикл.
 */
function reloadSpent(): boolean | null {
  try {
    return sessionStorage.getItem(RELOADED_FLAG) !== null;
  } catch {
    return null;
  }
}

/** `false` — записать флаг не удалось, значит и перезагружаться нельзя (см. выше про цикл). */
function spendReload(): boolean {
  try {
    sessionStorage.setItem(RELOADED_FLAG, '1');
    return true;
  } catch {
    return false;
  }
}

export function installChunkReload(
  reload: () => void = () => location.reload(),
  serverReachable: () => Promise<boolean> = serverIsUp,
): () => void {
  // Один провалившийся экран может дать несколько событий подряд (у чанка бывает несколько
  // зависимостей, и `preload` сообщает о каждой). Опрашивать сервер на каждое незачем.
  let deciding = false;
  const onPreloadError = () => {
    if (deciding) return;
    // null (хранилище недоступно) и true (попытка потрачена) одинаково означают «не мы».
    if (reloadSpent() !== false) return;
    deciding = true;
    void (async () => {
      // Флаг тратится ТОЛЬКО перед фактической перезагрузкой: если сервер молчит, попытка
      // остаётся при нас, и следующий провал — уже при живом сервере — будет вылечен.
      if ((await serverReachable()) && spendReload()) {
        reload();
        return;
      }
      deciding = false;
    })();
  };
  window.addEventListener('vite:preloadError', onPreloadError);
  return () => window.removeEventListener('vite:preloadError', onPreloadError);
}
