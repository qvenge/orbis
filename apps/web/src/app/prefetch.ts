/**
 * Фоновая догрузка чанков частых экранов.
 *
 * Разбиение бандла экономит первый кадр, но платит за это ожиданием ровно в тот момент,
 * когда пользователь уже нажал. Догружаем те же модули в фоне, как только браузер
 * освободился, — тогда лень остаётся невидимой: к моменту тапа чанк уже в памяти
 * (повторный `import()` того же модуля сеть не трогает, браузер отдаёт запись из module map).
 *
 * КОГО тянем и почему именно их:
 * - Экран сущности — всем. Он открывается тапом из обзора, повестки и чата, доступен на
 *   любой вкладке и никакими настройками не выключается; при этом он же и самый тяжёлый
 *   чанк разбиения.
 * - Budget — ТОЛЬКО тем, у кого вкладка реально есть. Она под гейтом installedViews
 *   (useBudget.ts:39, 03-budget §1.2), и у пользователя без установленного view экран
 *   недостижим ни одной кнопкой — его чанк для такого пользователя чистая трата трафика.
 *   Гейт достаётся бесплатно: тот же `user.getSettings` уже спрашивают TabBar и SidebarNav,
 *   лишнего запроса третий подписчик не делает.
 * - ImportFlow, CategoryScreen, TransactionsScreen, RolloverScreen — НЕ тянем. Разовый
 *   мастер и три экрана второго уровня внутри Budget: тащить их всем ради жеста, который
 *   в сессии может не случиться ни разу, дороже, чем показать на нём заглушку.
 *
 * Планировщик — `requestIdleCallback`; его нет в Safari до 17 и в jsdom, поэтому фолбэк на
 * `setTimeout`. Возвращаемая функция снимает ЗАПЛАНИРОВАННУЮ, но ещё не начатую догрузку:
 * размонтировали приложение (в бою — почти никогда, в тестах — после каждого теста) — и
 * фоновая работа не переживает того, ради кого затевалась.
 *
 * Ошибки догрузки проглатываются намеренно и полностью — см. `prefetchInFlight` ниже.
 */

/** Догрузка стартует, только когда браузер простаивает; потолок ожидания — чтобы на вечно
 *  занятой странице она случилась хоть когда-то. */
const IDLE_TIMEOUT_MS = 3000;
/** Фолбэк без requestIdleCallback: заведомо после первого кадра и первых запросов данных. */
const FALLBACK_DELAY_MS = 1500;

/**
 * Одна догрузка. Результат — по записи на каждый затребованный экран, и все они `settled`:
 * отказ фоновой догрузки не исключение, а обычный исход (см. `prefetchInFlight`).
 */
export type PrefetchTask = () => Promise<PromiseSettledResult<unknown>[]>;

/** Планировщик догрузки: получает задачу, возвращает функцию отмены. */
export type PrefetchSchedule = (task: PrefetchTask) => () => void;

const idle: PrefetchSchedule = (task) => {
  const run = () => {
    void task();
  };
  if (typeof requestIdleCallback === 'function') {
    const id = requestIdleCallback(run, { timeout: IDLE_TIMEOUT_MS });
    return () => cancelIdleCallback(id);
  }
  const id = setTimeout(run, FALLBACK_DELAY_MS);
  return () => clearTimeout(id);
};

/**
 * Счётчик догрузок в полёте.
 *
 * Нужен `installChunkReload`: vite шлёт `vite:preloadError` на ЛЮБОЙ провалившийся
 * динамический import, не отличая тот, что пользователь запросил, от нашего фонового. Без
 * этого флага провал фоновой догрузки перезагружал бы страницу под руками у человека,
 * который в этот момент ничего не просил, — и заодно тратил бы единственный на сессию
 * вкладки автоперезаход на отказ, которого никто не заметил.
 *
 * Починка при этом не теряется, а лишь откладывается до момента, когда она действительно
 * нужна. Провалившийся модуль остаётся в module map документа записью об ошибке, поэтому
 * когда пользователь всё-таки откроет этот экран, его собственный `import()` откажет сразу
 * же — уже как пользовательский, с флагом в нуле, — и `installChunkReload` перезагрузит
 * страницу тогда. То есть поведение возвращается ровно к тому, каким было до фоновой
 * догрузки: перезаход строго в ответ на жест.
 *
 * Цена — узкая гонка: если пользовательский чанк провалится РОВНО пока в полёте фоновая
 * догрузка, автоперезахода не будет и человек увидит кадр ChunkErrorBoundary с кнопкой
 * «Обновить». Окно — время одной догрузки; сценарий предполагает, что сеть в этот момент
 * уже сломана, и перезагрузка всё равно ничего бы не починила.
 */
let inFlight = 0;

export function prefetchInFlight(): boolean {
  return inFlight > 0;
}

function load(opts: { budget: boolean }): Promise<PromiseSettledResult<unknown>[]> {
  // Счётчик поднимаем ДО первого import(): дальше внутрь заходит vite-хелпер preload,
  // и провал должен застать флаг уже поднятым.
  inFlight++;
  const loads: Promise<unknown>[] = [import('../features/entity-detail/DetailScreen')];
  if (opts.budget) loads.push(import('../features/budget/BudgetScreen'));
  // allSettled, а не all: отказ фоновой догрузки — не событие. Он не должен ни всплывать
  // unhandled rejection'ом в консоль, ни доходить до кого-либо ещё.
  return Promise.allSettled(loads).finally(() => {
    inFlight--;
  });
}

/**
 * Планирует фоновую догрузку. `budget` — видна ли пользователю вкладка Budget
 * (`useBudgetTabVisible`). Возврат — отмена ещё не начатой догрузки.
 */
export function prefetchScreens(
  opts: { budget: boolean },
  schedule: PrefetchSchedule = idle,
): () => void {
  return schedule(() => load(opts));
}
