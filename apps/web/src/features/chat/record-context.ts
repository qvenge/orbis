/**
 * Сообщение чата про запись (спека 1б §6.4, РП-27): ссылка на запись — первой строкой, обычной
 * ссылкой `[[entity:<id>]]`, как её пишет и читает агент. Отдельного поля контекста у сообщения нет:
 * агент видит контекст тем же путём, что любую ссылку в тексте.
 */
export function withRecordContext(text: string, entityId: string): string {
  return `[[entity:${entityId}]]\n${text}`;
}
