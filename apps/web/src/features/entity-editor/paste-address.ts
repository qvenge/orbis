import { recordIdOfUrl } from '@orbis/shared/nav';

/**
 * Вставленный в тело текст → id записи, если это адрес Orbis (спека 1б §7.4); иначе `null`.
 *
 * Адрес — только если ВЕСЬ вставленный текст один адрес записи своего origin: текст с адресом внутри
 * вставляется как есть (ссылка посреди фразы — чужое решение, не наше). Края — пробелы и переводы
 * строки — снимаются: адресная строка и почтовые клиенты кладут адрес с хвостовым `\n` (перенос гейта
 * задачи 14). Разбор — `recordIdOfUrl` (`@orbis/shared/nav`): тот же, что у ссылок, так что вставка и
 * «Скопировать ссылку» понимают одно и то же. Старые ссылки Бюджета и тредов (`/budget/category/<id>`,
 * `/thread/<id>`) — `null`, остаются текстом (принято в гейте 14).
 */
export function pastedRecordId(text: string, origin: string): string | null {
  return recordIdOfUrl(text.trim(), origin);
}
