import { layoutMisplaced } from '@orbis/shared/doc/placement';
import { Extension } from '@tiptap/core';
import { Plugin, PluginKey } from '@tiptap/pm/state';

/**
 * Страж глубины узлов страницы (спека страниц 1а §5.2, §5.8): отменяет шаг, после которого
 * контейнер встал бы глубже `CONTAINER_LIMITS.depth`.
 *
 * Место узла страницы держит схема (группа `pageBlock`, спека 1б §10): контейнер, блок обвязки и
 * карточку пускают только верх документа и части контейнеров, так что вставка своего буфера в
 * пункт списка, перетаскивание в цитату и обёртки StarterKit (`Mod-Shift-b`, `Mod-Shift-8` над
 * выделением через блок записи) такого документа не соберут — ProseMirror держит `content` в
 * каждой транзакции. Глубину схема без группы на каждый уровень не выражает, а колонки третьим
 * уровнем меню «/» не предложит, но вставка буфера и перетаскивание положат. Сохранение такого
 * документа не пережило бы сверки скелета: ВСЁ тело ушло бы в один `rawBlock`, которого в
 * «Настроить» не поправить. Поэтому защита стоит на транзакции, а не на каждом входе: правило одно
 * (`layoutMisplaced`, та же копия, что у меню), входы — любые.
 *
 * Отменяется только ПЕРЕХОД из порядка в беспорядок: в редакторе, который УЖЕ показывает документ
 * с нарушением, правки не блокируются. Граница (фикс-раунд 1 гейта фикс-волны, M-2): `setContent`
 * — тоже транзакция, и подмена документа В ПОРЯДКЕ на документ с нарушением отменяется так же
 * молча; `BodyEditor` при этом уже считает подменённый документ показанным (`lastAccepted`,
 * `onAccept`). Путь сегодня недостижим: сервер такой документ в `body_doc` не кладёт (страховка
 * скелета уводит его в `rawBlock` — рядовой узел, законный везде), а редактор его не порождает —
 * этот же страж.
 *
 * Расширение плагинное, без нод и марок: схема редактора остаётся равной схеме документа.
 */
export const LayoutGuard = Extension.create({
  name: 'layoutGuard',
  addProseMirrorPlugins() {
    return [
      new Plugin({
        key: new PluginKey('layoutGuard'),
        filterTransaction: (tr, state) =>
          !tr.docChanged || !layoutMisplaced(tr.doc) || layoutMisplaced(state.doc),
      }),
    ];
  },
});
