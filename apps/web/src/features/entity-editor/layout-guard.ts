import { layoutMisplaced } from '@orbis/shared/doc/placement';
import { Extension } from '@tiptap/core';
import { Plugin, PluginKey } from '@tiptap/pm/state';

/**
 * Страж места узлов страницы (спека страниц 1а §5.2, §5.8): отменяет шаг, после которого
 * контейнер, блок обвязки или карточка оказались бы вне верха тела и частей контейнера — или
 * контейнер встал бы глубже `CONTAINER_LIMITS.depth`.
 *
 * Меню «/» такие места уже не предлагает, но меню — лишь один вход. Схема документа пускает эти
 * узлы в пункт списка, цитату и ячейку (`block+`), и туда же их кладут вставка своего буфера,
 * перетаскивание и обёртки StarterKit (`Mod-Shift-b`, `Mod-Shift-8` над выделением через блок
 * записи). Сохранение такого документа не пережило бы сверки скелета: ВСЁ тело ушло бы в один
 * `rawBlock`, которого в «Настроить» не поправить. Поэтому защита стоит на транзакции, а не на
 * каждом входе: правило одно (`layoutMisplaced`, та же копия, что у меню), входы — любые.
 *
 * Отменяется только ПЕРЕХОД из порядка в беспорядок: документ, приехавший уже с нарушением
 * (`setContent`), не застревает, и правки внутри него не блокируются. Недопустимый жест просто
 * не применяется — схему (группу узлов) здесь не сужаем: это смена серверной валидации.
 *
 * Расширение плагинное, без нод и марок: схема редактора остаётся равной схеме документа.
 */
export const LayoutGuard = Extension.create({
  name: 'layoutGuard',
  addProseMirrorPlugins() {
    return [
      new Plugin({
        key: new PluginKey('layoutGuard'),
        filterTransaction: (tr, state) =>
          !tr.docChanged || !layoutMisplaced(tr.doc) || layoutMisplaced(state.doc),
      }),
    ];
  },
});
