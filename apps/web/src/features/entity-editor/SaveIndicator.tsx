import { useEffect, useState } from 'react';
import type { BodySaveState } from './useBodySave';

/**
 * Сколько запрос должен идти, чтобы о нём вообще стоило говорить. Обычное сохранение
 * укладывается в круг быстрее, и надпись успела бы только моргнуть — это шум, а не ответ.
 */
export const SLOW_SAVE_MS = 1000;

/**
 * Состояние сохранения тела — в углу и молча.
 *
 * Успех НЕ празднуем. Постоянный статус в углу — ровно та панель инструментов над каждой
 * заметкой, от которой экран отказывается сознательно; молчание здесь и означает «всё
 * сохранено». Показать есть что ровно в трёх случаях: запрос идёт дольше секунды, правка не
 * сохранена и правку ОТВЕРГЛИ.
 *
 * Последние два — разные вещи, и одним словом их не назвать. «Не сохранено» — обещание
 * повторить, и для сетевого отказа оно правда: следующее нажатие клавиши заводит новую попытку.
 * Для терминального (VALIDATION серверного гейта — битый документ или чужая версия схемы) это
 * ложь: повтора не будет НИКОГДА, и человек, ожидающий, что «само дойдёт», просто потеряет
 * набранное. Поэтому у него своя строка — с единственным действием, которое помогает.
 *
 * Выдержка живёт ЗДЕСЬ, а не в хуке: `state` обязан отвечать, что происходит на самом деле,
 * иначе Задача 14 (черновик) читала бы «idle» у сохранения в полёте.
 *
 * `self-end` — на самих строках, а не на обёртке снаружи. Обёртка была бы ребёнком полосы
 * плашек ВСЕГДА, в том числе когда индикатор молчит, и `empty:hidden` на полосе не срабатывал бы
 * никогда: над вкладками висел бы постоянный отступ там, где сказать нечего. Вне flex-контейнера
 * класс не значит ничего и не мешает.
 */
export function SaveIndicator({ state }: { state: BodySaveState }) {
  const [slow, setSlow] = useState(false);

  useEffect(() => {
    if (state !== 'saving') {
      setSlow(false);
      return;
    }
    const id = window.setTimeout(() => setSlow(true), SLOW_SAVE_MS);
    return () => clearTimeout(id);
  }, [state]);

  // role="status", а не alert: строка живёт в углу и меняется вместе с состоянием — прерывать
  // ею чтение нечем, а «Не сохранено» никуда не денется, пока правка не доедет.
  if (state === 'rejected') {
    return (
      <span role="status" data-testid="save-indicator" className="self-end text-xs text-danger">
        Правка отклонена — обновите страницу
      </span>
    );
  }
  if (state === 'error') {
    return (
      <span role="status" data-testid="save-indicator" className="self-end text-xs text-danger">
        Не сохранено
      </span>
    );
  }
  if (state === 'saving' && slow) {
    return (
      <span role="status" data-testid="save-indicator" className="self-end text-xs text-text-muted">
        Сохраняем…
      </span>
    );
  }
  return null;
}
