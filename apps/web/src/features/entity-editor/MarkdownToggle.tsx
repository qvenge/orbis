import { type BodyDoc, parseBody, serializeBody } from '@orbis/shared/doc';
import { useMemo, useState } from 'react';
import { Button } from '../../ui/Button';

/**
 * Предупреждение о неразобранной разметке. Второе «Применить» — не украшение: `parseBody`
 * никогда не бросает и молча уводит непонятое в `rawBlock` дословно, так что без явного
 * подтверждения человек решил бы, что его разметку разобрали.
 */
const RAW_WARNING =
  'Часть разметки не разобрана — эти блоки сохранятся дословно, «как есть». ' +
  'Нажмите «Применить» ещё раз, чтобы подтвердить.';

/**
 * Тексты неразобранных блоков документа.
 *
 * Верхнего уровня ДОСТАТОЧНО, слепого пятна нет: `parseBody` создаёт rawBlock в трёх местах
 * (`convert.ts`: ветка reference-определений, цикл по токенам верхнего уровня, аварийный catch)
 * и все три кладут его в КОРЕНЬ документа, а своего парсера у ноды нет вовсе
 * (`nodes/raw.ts`, `parseHTML: () => []`) — создать её глубже некому.
 */
function rawTexts(doc: BodyDoc['doc']): string[] {
  return (doc.content ?? []).flatMap((node) =>
    node.type === 'rawBlock'
      ? [typeof node.attrs?.markdown === 'string' ? node.attrs.markdown : '']
      : [],
  );
}

/**
 * Правка тела как markdown — для тех, кто пишет разметку руками, и как окно в то, что реально
 * лежит в `body` (а лежит там ровно эта строка: FTS, промпт и MCP читают её же).
 *
 * Экран монтирует тумблер ТОЛЬКО через `lazy()`: значимый импорт `@orbis/shared/doc` тянет всю
 * схему документа (~156 kB gzip), и статический импорт утащил бы её в первый кадр записи.
 */
export function MarkdownToggle({
  doc,
  onChange,
  onClose,
}: {
  doc: BodyDoc;
  onChange: (doc: BodyDoc) => void;
  onClose: () => void;
}) {
  // Мемо, а не голый вызов: сериализация зовётся при КАЖДОМ рендере, то есть на каждое нажатие
  // клавиши в поле, и стоит ~1 мс на теле из сорока блоков (замерено) — платить эту миллисекунду
  // за символ не за что. Показанная строка — канон, ровно содержимое колонки `body`.
  // База сравнения ПОДВИЖНА: придёт новый `doc` (правка с другого устройства) — `initial`
  // пересчитается, и «без изменений» будет считаться относительно НОВОГО документа. Так и
  // задумано: писать поверх чужой правки то же самое незачем.
  const initial = useMemo(() => serializeBody(doc), [doc]);
  /**
   * Что в этом теле НЕ разобрано было и ДО правки. Предупреждаем только о НОВОМ: тело, в
   * котором картинка лежала с самого начала, иначе требовало бы подтверждения на каждую правку —
   * хоть на исправленную опечатку в соседнем абзаце, — и двухшаговость выродилась бы в лишний
   * клик, который перестают читать через день.
   *
   * Множество, а не счётчик: продублировать УЖЕ лежащую в теле картинку — не новая непонятая
   * разметка, а копия старой; спрашивать о ней не о чем. Ровно тот же документ, что показан в
   * поле, — база сравнения подвижна вместе с `initial` (см. выше).
   */
  const knownRaw = useMemo(() => new Set(rawTexts(doc.doc)), [doc]);
  // А вот `text` — снимок на момент открытия: набранное пользователем НЕ перетирается
  // приходящим `doc` (автосохранение Задачи 13 отдаёт новый объект документа на каждый круг
  // записи, и живое обновление стирало бы набранный текст под руками).
  const [text, setText] = useState(initial);
  // ОДНО состояние на подтверждение и предупреждение, а не два: они всегда поднимаются и
  // гаснут вместе, и разъехаться им можно было бы только по ошибке.
  const [awaitingRawConfirm, setAwaitingRawConfirm] = useState(false);

  /**
   * ЕДИНСТВЕННАЯ дверь наружу: плашка гаснет вместе с уходом, каким бы путём он ни случился.
   *
   * Своя дверь у «Отмены» была бы обходом всей двухшаговости, а не мелкой асимметрией. Сегодня
   * экран тумблер РАЗМОНТИРУЕТ (DetailScreen рисует его по условию `asMarkdown`), то есть флаг
   * умирает и сам, — но держаться на этом нельзя: скрытие вместо размонтирования выглядит
   * невинной правкой раскладки, а цена ей — сохранение raw с ПЕРВОГО «Применить» при следующем
   * открытии, без предупреждения вообще.
   */
  function close() {
    setAwaitingRawConfirm(false);
    onClose();
  }

  function apply() {
    // Без изменений — без записи: лишняя мутация подняла бы updated_at ни за что.
    if (text === initial) {
      close();
      return;
    }
    const next = parseBody(text);
    // Спрашиваем ПОБЛОЧНО и только о новом: непонятое уезжает в raw блок за блоком, и частичная
    // неразобранность (абзац + картинка) — самый обычный случай. Непонятое внутри блока
    // (картинка в цитате, в пункте списка, в ячейке таблицы) утаскивает в raw ВЕСЬ верхний блок
    // целиком — проверено пробой на пяти вложениях, но держится это на построении, а не на
    // выборке.
    const hasNewRaw = rawTexts(next.doc).some((markdown) => !knownRaw.has(markdown));
    if (hasNewRaw && !awaitingRawConfirm) {
      // НЕ закрываемся: в закрытом тумблере предупреждения не увидел бы никто, а юнит-тест
      // остался бы зелёным — спай `onClose` компонент не размонтирует (ревью И12).
      setAwaitingRawConfirm(true);
      return;
    }
    onChange(next);
    close();
  }

  return (
    // Escape — общий жест «уйти отсюда» во всём приложении, и здесь он ведёт в ТУ ЖЕ дверь,
    // что «Отмена»: своя ветка обошла бы двухшаговость (см. `close` выше). Слушает вся форма,
    // а не одно поле: после «Применить» фокус на кнопке, и Escape оттуда обязан работать так же.
    //
    // Обработчик на неинтерактивном контейнере — намеренно. Роль ему не нужна и вредна: внутри
    // живут поле и кнопки, а «клавиатурный двойник» тут не требуется — жест сам и есть
    // клавиатурный, мышиного двойника у него нет.
    // biome-ignore lint/a11y/noStaticElementInteractions: клавиатурный жест поверх формы, см. выше
    <div
      className="flex flex-col gap-2"
      onKeyDown={(e) => {
        if (e.key !== 'Escape') return;
        e.stopPropagation(); // Escape съеден здесь: закрывать заодно и экран снаружи незачем
        close();
      }}
    >
      <textarea
        data-testid="markdown-source"
        aria-label="Тело записи как markdown"
        value={text}
        spellCheck={false}
        onChange={(e) => {
          setText(e.target.value);
          // Подтверждение и предупреждение относятся к ПРЕЖНЕМУ тексту: новый разбирается
          // заново, и переносить на него согласие «сохранить как есть» нельзя.
          setAwaitingRawConfirm(false);
        }}
        // Кольцо фокуса, а не голый outline-none: поле без рамки лежит прямо на листе, и с
        // погашенным контуром пришедшего табуляцией фокуса не видно вовсе.
        className="min-h-64 w-full resize-none rounded-lg bg-transparent px-2 py-1.5 font-mono text-sm focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-accent/30"
      />
      {awaitingRawConfirm && (
        // text-alert, а НЕ text-warning: --color-warning объявлен цветом заливки бара и на
        // белом листе даёт 3.18:1 (документировано в NativeRow.tsx:92, GoalProgress.tsx:55-57).
        <p role="alert" className="text-sm text-alert">
          {RAW_WARNING}
        </p>
      )}
      <div className="flex justify-end gap-2">
        <Button variant="ghost" size="sm" onClick={close}>
          Отмена
        </Button>
        <Button size="sm" onClick={apply}>
          Применить
        </Button>
      </div>
    </div>
  );
}
