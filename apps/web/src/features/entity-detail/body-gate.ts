import type { BodyGate } from './EntityBody';

/**
 * Неотправленная правка тела перед жестом, который уводит с тела или переписывает запись (С1а-8
 * «текст не теряется»; финальное ревью 1а, F-I1; остаток 1а №86).
 *
 * Одно правило на меню «⋯» (жесты, пишущие пачку) и настройку страницы или шаблона («Готово»,
 * «назад», смена записи — страж ухода `state/leave-guard.ts`). Модуль эагерный и лёгкий: его зовёт
 * настройка в первом кадре экрана записи, а меню — ленивый чанк, и держать тексты в нём значило бы
 * тянуть чанк меню ради двух строк.
 */

/** Тост жеста, отложенного ради неотправленной правки тела (`settleBody`). */
export const BODY_SAVING = 'Сохраняем текст…';
/** Тост жеста при правке тела, которую сервер отверг или вернул конфликтом: досылать бесполезно. */
export const BODY_BLOCKED =
  'Правка текста не сохранена — сначала разберитесь с плашкой над записью';

/**
 * Можно ли действовать прямо сейчас. Пока у тела есть неотправленное (пауза набора или сохранение
 * в полёте), жест не исполняется: тело досылается сейчас же, человек видит тост и повторяет жест,
 * когда текст сохранён. Правку, которую сервер отверг или вернул конфликтом, повторный досыл не
 * спасёт — не шлём и говорим правду (`BODY_BLOCKED`).
 */
export function settleBody(
  gate: BodyGate | null,
  show: (text: string, tone: 'default' | 'danger') => void,
): boolean {
  if (gate === null || !gate.hasUnsent()) return true;
  if (gate.blocked()) {
    show(BODY_BLOCKED, 'danger');
    return false;
  }
  gate.flush();
  show(BODY_SAVING, 'default');
  return false;
}
