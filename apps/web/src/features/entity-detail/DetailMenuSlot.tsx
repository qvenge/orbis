/**
 * Точка лени меню «⋯» экрана записи: пункты раздела «Этот экран» (`DetailMenu`) живут в своём чанке
 * (рычаг веса РП-11 задачи 14 страниц 1а: Radix-меню — самый крупный кусок, которому в первом кадре
 * делать нечего). Кнопку «⋯» рисует присутствие хоста (срез 1б §6.4, `app/frame/ScreenMenu.tsx`), а
 * экран отдаёт ему ЭТОТ загрузчик контекстом `ScreenMenuProvider`. Промис загрузки один на
 * приложение.
 *
 * Отказ загрузки промис НЕ запоминает: отвергнутый промис в кеше делал бы кнопку мёртвой до
 * перезагрузки страницы, и следующее нажатие даже не попыталось бы снова.
 *
 * Модуль эагерный, но лёгкий: `DetailMenu` здесь только динамическим импортом (статический схлопнул бы
 * чанк — сторожа `check-lazy-chunks.ts` и `save.test.tsx`).
 */
let menuModule: Promise<typeof import('./DetailMenu')> | null = null;
const loadMenu = () => {
  menuModule ??= import('./DetailMenu').catch((error: unknown) => {
    menuModule = null;
    throw error;
  });
  return menuModule;
};

/**
 * Забыть загруженный модуль — ТОЛЬКО для тестов: без этого все тесты файла, кроме первого, шли бы
 * с уже загруженным меню, и «нажатие до загрузки чанка» не проверялось бы вовсе.
 */
export function resetDetailMenuModuleForTests(): void {
  menuModule = null;
}

/** Загрузчик содержимого меню — модульная константа: одна ссылка на функцию на всё приложение. */
export const loadDetailMenu = () => loadMenu().then((m) => m.DetailMenu);
