import { ownCardComponents } from './own-cards';
import { useRecordHost } from './record-host';

/**
 * `{{cards: own}}` (спека 1б §8.5) — свои карточки всех аспектов записи, у которых своя карточка есть
 * (ядра и расширений), кроме размещённых шаблоном явно (`placed` — аспекты `{{card: X}}` дерева), В
 * ПОРЯДКЕ РАНГОВ КАРТОЧЕК. Ранги поставки воспроизводят порядок 1а — цель, исполнитель, рутина,
 * прогон, финансы, — поэтому шаблон хоста, не называя расширений, рисует тот же экран (С1б-9).
 *
 * Порядок — ранг КАРТОЧКИ (`ownCardComponents()`), а не место аспекта в реестре: карточка исполнителя
 * показывается и у простой задачи, и по аспекту задачи она встала бы после финансов (М-1 ревью
 * спеки).
 *
 * Без обёртки: каждая карточка — прямой сосед блоков дерева, как стояли пять строк `{{card: X}}`
 * шаблона хоста 1а. Лишний узел с отступами дал бы пустую щель у записи без своих карточек.
 */
export function OwnCards({ placed }: { placed: ReadonlySet<string> }) {
  const { entity } = useRecordHost();
  return (
    <>
      {ownCardComponents()
        .filter((c) => !placed.has(c.aspect) && c.showWhen(entity))
        .map(({ aspect, Card }) => (
          <Card key={aspect} />
        ))}
    </>
  );
}
