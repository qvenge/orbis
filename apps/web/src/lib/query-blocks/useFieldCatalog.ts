import { useMemo } from 'react';
import { useRegistry } from '../registry/useRegistry';
import { type QueryRegistry, registryOf } from './catalog';

export interface FieldCatalogState {
  /** null — реестр ещё едет; потребитель обязан показать загрузку, а не пустой каталог. */
  registry: QueryRegistry | null;
}

/**
 * Реестр запросов (§А2-2, §А5-3а) — ОДИН источник на всех потребителей блоков: виджет,
 * строковый редактор и форма-редактор.
 *
 * Источник — `registry.effective` (§А9-2), а не встроенные словари из shared: реестр живёт
 * в БД (там же приезжают пользовательские свойства и аспекты), и статика показывала бы форме
 * поля, которых на сервере нет, а те, что есть, прятала.
 *
 * Запрос ОДИН, и это главное, что здесь изменилось. Раньше их было два (`aspect.list` +
 * `aspect.properties`), и до готовности ОБОИХ каталога не было вовсе — иначе на половине
 * снимка разбор врал бы `UNKNOWN_ROLE` там, где имя просто ещё не доехало. Теперь половины
 * снимка не существует по построению: три словаря приезжают одним ответом и с одной версией,
 * и «что считать полным снимком» больше не вопрос клиента.
 *
 * Тот же снимок и тот же кеш, что у подписей полей (`useRegistry`): каталог формы и подпись
 * строки на записи обязаны говорить об одном свойстве одно и то же слово.
 */
export function useFieldCatalog(): FieldCatalogState {
  const registry = useRegistry();
  const data = registry.data;
  return useMemo(() => ({ registry: registryOf(data) }), [data]);
}
