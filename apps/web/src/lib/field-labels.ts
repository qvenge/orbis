// Подписи агрегатов query_result — единственный словарь подписей, оставшийся в коде web.
//
// Почему он ЗДЕСЬ, а не в реестре. `op` агрегата (`sum`, `count`, …) — часть ГРАММАТИКИ
// запроса (§6.1/§А5-7), а не запись реестра: у него нет ни id, ни владельца, ни label в
// jsonb, и переименовать его владелец не может — это ключевое слово языка. Словарь по
// закрытому союзу ключевых слов ничем не отличается от подписи кнопки.
//
// Всё остальное, что раньше лежало в этом файле (подписи полей аспектов и подписи самих
// аспектов), уехало в реестр Задачей 13a: см. `lib/registry/labels.ts`. Возвращать сюда
// карты вида «имя поля → русское слово» нельзя — на это стоит греп-тест `field-labels.test.ts`.
const AGGREGATE_LABELS: Record<string, string> = {
  sum: 'сумма',
  count: 'количество',
  avg: 'среднее',
  min: 'минимум',
  max: 'максимум',
};

export function aggregateLabel(op: string): string {
  return AGGREGATE_LABELS[op] ?? op;
}
