// Инвалидация кэша графа после мутации (решение Р17 фазы E).
//
// `entity.query`, `entity.get` и `entity.count` — три взгляда на ОДИН граф, и протухают
// они вместе.
// Раньше это было не так: списки инвалидировались всегда, а detail — только точечно, по
// id правленой сущности. Следствия были видны глазом:
//   • прогресс цели (§11.3) не менялся после добавления подходящей записи, хотя сервер
//     считает его на каждом чтении entity.get — открытая цель просто не перечитывалась;
//   • backlinks и подзадачи открытой сущности не подхватывали созданное в другом месте;
//   • переименование сущности не доезжало ни до её строки в чужих подзадачах и чужих
//     backlinks, ни до строк query_result в чате, ни до закреплённых: у каждого из них
//     СВОЙ ключ entity.get — `{id}` у EntityRef, `{id, include:['body']}` у PinnedList, —
//     и точечная инвалидация detail (`{id, include:[body,relations,backlinks,thread]}`)
//     не совпадала ни с одним, а backlinks и вовсе приезжают внутри ответа СОСЕДНЕЙ
//     сущности. (Разметку `[[entity:…]]` это не касается вовсе: её рисует
//     lib/markdown/Markdown.tsx подписью из самой ссылки, ничего не дочитывая.)
//   • бейдж закреплённого smart-list'а (`entity.count`, PinnedList) пересчитывался
//     только после fast-path: после подтверждения пачки, Undo, импорта или новой
//     подзадачи он показывал вчерашнее число.
//
// Цена честная и небольшая. Смонтирован всегда ОДИН экран (router.tsx рисует только
// активную вкладку), поэтому перечитываются лишь его entity.get: сам detail плюс мелкие
// чтения по id у EntityRef/PinnedList. Записи неактивных экранов сеть не трогают вовсе —
// они помечаются протухшими и перечитаются, когда экран откроют, что и есть нужное
// поведение: цель, открытая после записи в чате, обязана показать новое число.
// Точнее клиент выбрать не может: какие именно цели и списки задевает новая запись,
// знает только сервер, обходя граф запросом.
//
// Прецедент ровно этого приёма уже был в PlannedToFactCard (план→факт трогает и суммы,
// и связи) — здесь он назван и объяснён в одном месте вместо копии на каждой мутации;
// сам PlannedToFactCard переведён на этот помощник, чтобы источник приёма и приём не
// разъезжались.
import type { trpc } from '../trpc';

/**
 * Звать после ЛЮБОЙ мутации, меняющей граф: создание, удаление/Undo, правка аспектов,
 * подтверждение рискованной пачки, сид, материализация повторяющихся, слив
 * retry-буфера. Покрытие сверено дважды: на круге правок 1 — по списку `useMutation`
 * web, на круге правок 2 — по путям записи МИМО них (буфер уходит vanilla-клиентом, и
 * первая сверка его не увидела). Непокрытых путей правки графа не осталось, кроме
 * одного названного:
 *   • `Blocks.tsx` инвалидирует три ключа точечно (обе стороны связи + списки). Связь
 *     blocks касается ровно двух сущностей, и они там уже перечитываются обе; известная
 *     щель — цель, чей запрос использует excludeBlocked, пересчитается при следующем
 *     открытии.
 * Мутации, графа НЕ меняющие, сюда сознательно не заходят: `ai.reject` и
 * `ai.declineMemoryRule` пишут в append-only chat_messages, `import.analyze`/`review` —
 * чтения (withIdentity + select), `chat.ensureThread` заводит тред, `user.updateSettings`
 * — настройки.
 *
 * Бюджетные агрегаты этим не покрываются — у них свой invalidateBudget (03-budget).
 */
export function invalidateGraph(utils: ReturnType<typeof trpc.useUtils>): void {
  void utils.entity.query.invalidate();
  void utils.entity.get.invalidate();
  // Третий ключ, а не «на всякий случай»: бейджи закреплённых smart-list'ов
  // (PinnedList) считают элементы отдельным запросом, и без него счётчик врал бы
  // ровно там, где список рядом уже обновился.
  void utils.entity.count.invalidate();
}
