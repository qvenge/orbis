/**
 * Страж ухода с экрана (остаток 1а №86): экран с неотправленной правкой говорит «нет» переходу, и
 * переход не случается.
 *
 * Зачем. Настройка страницы или шаблона досылает отложенную правку тела при размонтировании
 * (`useBodySave`), но о досыле, который сервер отверг, сказать уже некому: плашки тела уходят
 * вместе с видом. «Готово», «назад» и смена записи молча теряли бы текст. Поэтому экран, у которого
 * есть что терять, регистрирует стража, а переходы спрашивают его ДО того, как сменить экран.
 *
 * Все переходы стора навигации (`push`, `switchTab`, `resetTabToRoot`, `closeToBudgetOverview`),
 * «назад» (`goBack`) и системный жест (`popstate` в `installHistorySync`) зовут `mayLeave()`. Новая
 * модель истории и рамка приложения (задачи 15 и 19 среза 1б) ОБЯЗАНЫ звать `mayLeave()` во всех
 * своих переходах: переход мимо стража снова терял бы правку молча.
 *
 * Модуль листовой и без React: его зовёт стор навигации, который грузится в первом кадре.
 */

/** Страж: `true` — уйти можно; `false` — нельзя, и страж сам объяснил человеку почему (тост). */
export type LeaveGuard = () => boolean;

const guards = new Set<LeaveGuard>();

/** Зарегистрировать стража; возвращает снятие — удобно отдавать из `useEffect`. */
export function registerLeaveGuard(guard: LeaveGuard): () => void {
  guards.add(guard);
  return () => {
    guards.delete(guard);
  };
}

/** Можно ли уйти с экрана. Страж, сказавший «нет», сам объяснил человеку почему (тост). */
export function mayLeave(): boolean {
  for (const g of guards) if (!g()) return false;
  return true;
}
