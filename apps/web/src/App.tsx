import { useEffect } from 'react';
import { AppShell } from './app/AppShell';
import { externalEntryPath, installHistorySync, openDeepLink } from './app/history';
import { useRetryFlush } from './state/retry';

export function App() {
  // §2.6/§5.3: досыл retry-буфера при старте (онлайн) и переходе offline→online.
  useRetryFlush();
  // §9.4: настройки — сквозной экран; открываются из sidebar (десктоп)
  // и из шапки экрана (мобила), см. SidebarNav / ScreenHeader.

  // Навигация ↔ история браузера (D18) и вход снаружи (§1.3). Порядок строк здесь —
  // требование, а не стиль: `installHistorySync` первым делом канонизирует адрес под
  // ТЕКУЩУЮ позицию стора (`replaceState`), то есть затирает входящий путь. Прочитанный
  // после установки `location.pathname` был бы уже подменённым, и внешний вход не работал
  // бы никогда. Поэтому адрес снимается ДО установки — снимком в локальную переменную,
  // а не параметром `installHistorySync`: синхронизация отвечает за согласие стора
  // с историей, разбор входящей ссылки — за стартовую позицию, и одна функция на две
  // обязанности тут ничего не упрощает.
  //
  // Больше того, порядок «сначала установка, потом ссылка» работает НА нас: подписка уже
  // стоит, и оба шага openDeepLink (корень целевой вкладки, затем сам экран) становятся
  // записями истории — первый «назад» у пришедшего по ссылке ведёт на корень вкладки,
  // а не из приложения.
  //
  // Эффект стоит ЗДЕСЬ, ниже OnboardingGate: до прохождения гейта App не монтируется,
  // адрес при этом никто не переписывает, и ссылка спокойно дожидается монтирования.
  useEffect(() => {
    const entryPath = externalEntryPath();
    const uninstall = installHistorySync();
    // null — вход не снаружи (перезагрузка, повторный прогон эффекта в StrictMode);
    // неразобранный путь ('/' и любой чужой) openDeepLink отвергает сам. В обоих случаях
    // остаётся восстановленная из persist позиция (§1.4).
    if (entryPath) openDeepLink(entryPath);
    return uninstall;
  }, []);

  return <AppShell />;
}
