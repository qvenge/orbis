import type { JSONContent, MarkdownRendererHelpers } from '@tiptap/core';
import CodeBlock from '@tiptap/extension-code-block';

/**
 * Длина ограды по CommonMark §4.5: `max(3, самая длинная серия обратных кавычек в содержимом + 1)`.
 *
 * Правило проверено РАЗБОРОМ, а не по документации: для десяти видов содержимого подобрана
 * минимальная длина ограды, при которой round-trip возвращает исходные байты, — и она совпала
 * с формулой везде, кроме `x``​`y`, где серия стоит не одна на строке и закрывающей оградой не
 * становится (хватает и трёх). Формула там даёт четыре — безопасный избыток: содержимое цело,
 * цена — лишняя кавычка в тексте.
 *
 * Спред в Math.max не используется намеренно: тело блока кода бывает длиной в десятки тысяч
 * символов, и `Math.max(...массив)` на таком входе кладёт стек.
 */
function fenceFor(content: string): string {
  let longest = 0;
  for (const run of content.matchAll(/`+/g)) longest = Math.max(longest, run[0].length);
  return '`'.repeat(Math.max(3, longest + 1));
}

/**
 * Блок кода с оградой ПО СОДЕРЖИМОМУ. Штатный сериализатор `@tiptap/extension-code-block`
 * (dist/index.js:81) печатает ровно три обратные кавычки всегда — и на приёме CommonMark
 * «ограда в ограде» (так показывают markdown внутри markdown, так модель штатно пишет примеры,
 * так кусок README попадает в блок кода вставкой) внутренняя ограда закрывала внешнюю:
 *
 *   исход  "````\n```\nвнутри\n```\n````"
 *   канон1 "```\n```\nвнутри\n```\n```"          — блок распался на два пустых и абзац
 *   канон2 "```\n\n```\n\nвнутри\n\n```\n\n```"  — то есть канон не был идемпотентен
 *
 * Второй, найденный пробой случай той же болезни — info-строка. Ограда `~~~` разрешает в ней
 * обратные кавычки, ограда из кавычек — НЕТ, поэтому `~~~a``​b` печаталось как ```` ```a`b ```` и блок кода
 * превращался в абзац с инлайн-кодом (`~~~a``​b\nx\n~~~` → ... → "`a`b x` "). Негодный ярлык
 * языка опускается: это подсказка подсветке, а не текст пользователя, и терять её — не потеря.
 *
 * Расширяется ИМЕННО отдельный `CodeBlock`, а StarterKit конфигурируется `codeBlock: false`
 * (см. schema.ts). Дописать вторую регистрацию поверх StarterKit нельзя: менеджер разметки
 * держит обработчики списком на имя ноды и берёт ПЕРВЫЙ (`getHandlerForToken`,
 * @tiptap/markdown/dist/index.js:475), то есть штатный так и остался бы за главного.
 */
export const OrbisCodeBlock = CodeBlock.extend({
  renderMarkdown: (node: JSONContent, h: MarkdownRendererHelpers) => {
    const language = typeof node.attrs?.language === 'string' ? node.attrs.language : '';
    const info = language.includes('`') ? '' : language;
    // Пустой блок кода — законное состояние редактора (нажали «Код» и ничего не набрали);
    // штатная реализация держала для него отдельную ветку, дающую ровно эту же строку.
    const body = node.content ? h.renderChildren(node.content) : '';
    const fence = fenceFor(body);
    return `${fence}${info}\n${body}\n${fence}`;
  },
});
