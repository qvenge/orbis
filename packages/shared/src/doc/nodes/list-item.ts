import type { JSONContent, MarkdownRendererHelpers, RenderContext } from '@tiptap/core';
import { ListItem } from '@tiptap/extension-list';

/**
 * Пункт списка БЕЗ хвостового пробела, когда он пуст.
 *
 * Найдено пробой (в брифе ревью этого нет). Живое состояние редактора «нажали кнопку списка и
 * ещё ничего не набрали» печаталось маркером с пробелом — `"- "`, `"1. "`, `"- [ ] "`, — а
 * такую строку marked списком НЕ СЧИТАЕТ: она разбирается в абзац с текстом «- », и канон
 * экранирует его в «\- ». То есть проекция самого частого состояния списка не была неподвижной
 * точкой, а страховка записи (bodyPairFromDoc) на ней срабатывала бы каждый круг автосохранения
 * и уводила бы ВЕСЬ документ в raw.
 *
 * Без пробела всё сходится (проверено разбором): `"-"` → bulletList с пустым пунктом → `"-"`.
 * Нумерованный `"1."` marked отдаёт пунктом без абзаца внутри — документом, непригодным по
 * схеме, — и его подхватывает страховка разбора в convert.ts, уводя блок в raw дословно;
 * проекция при этом тоже неподвижна.
 *
 * Условие УЗКОЕ намеренно, по двум причинам сразу. Первая: слепое `trimEnd()` съело бы два
 * хвостовых пробела мягкого переноса (hardBreak) в конце пункта, то есть чинило бы косметику
 * ценой потери переноса. Вторая: у ПУСТОЙ ЗАДАЧИ пробел, наоборот, НЕСУЩИЙ — `- [ ] ` marked
 * разбирает в чеклист, а `- [ ]` (без пробела) в обычный пункт с текстом `[ ]`, который канон
 * ещё и экранирует в `\[ \]` (замерено). Поэтому чекбоксная форма маркера сюда не входит — и по
 * той же причине `TaskItem` не оборачивается вовсе: его пустая проекция `- [ ] ` уже неподвижна.
 */
const MARKER_ONLY = /^[ \t]*(?:[-+*]|\d+[.)])[ \t]+$/;

/** Штатный сериализатор зовётся ЧЕРЕЗ конфиг базовой ноды: своей копии разметки списка (отступы
 *  вложенных блоков, нумерация, `start`) здесь быть не должно — она разошлась бы с библиотекой. */
const base = ListItem.config.renderMarkdown as
  | ((node: JSONContent, h: MarkdownRendererHelpers, ctx: RenderContext) => string)
  | undefined;

export const OrbisListItem = ListItem.extend({
  renderMarkdown: (node: JSONContent, h: MarkdownRendererHelpers, ctx: RenderContext): string => {
    const rendered = base?.(node, h, ctx) ?? '';
    return MARKER_ONLY.test(rendered) ? rendered.replace(/[ \t]+$/, '') : rendered;
  },
});
