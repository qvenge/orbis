import { MarkdownManager } from '@tiptap/markdown';

/**
 * Подмена для intraword `_` на время экранирования. NUL взят намеренно: CommonMark требует
 * заменять U+0000 ещё на входе, так что в разобранном тексте его быть не может. Пробел на этой
 * роли (первый набросок) уничтожал текст — обратная замена превращала в `_` ВСЕ пробелы.
 */
const UNDERSCORE_SLOT = '\u0000';

/**
 * Конструкции, оживающие ТОЛЬКО в начале строки. Общее правило экранирования их не ловит, а
 * штатный сериализатор прятал `>` за `&gt;` — заодно уродуя безобидное `2 > 1`. Экранируем
 * первый символ конструкции и только в начале текстового узла: лишний слэш в середине строки
 * безвреден (`\>` — это `>`), а пропущенный в начале превращает абзац в цитату при повторном
 * разборе.
 */
function escapeBlockStarter(text: string): string {
  // `1.` / `1)` — нумерованный список: экранируется разделитель, а не цифры.
  const ordered = text.replace(/^(\d{1,9})([.)])(?=\s|$)/, '$1\\$2');
  if (ordered !== text) return ordered;
  // `>` — цитата; `#…` — ATX-заголовок; `-`/`+` — маркер списка, `--` — ещё и тематический
  // разделитель (`*` и `_` в той же роли уже экранированы общим правилом).
  return /^(?:>|#{1,6}(?=\s|$)|[-+](?=[\s-]|$))/.test(text) ? `\\${text}` : text;
}

type TextNodeLike = { marks?: Array<string | { type: string }> };

/**
 * Канон без ЛИШНЕГО экранирования (вердикт по Б1, мера 2). Штатный сериализатор экранирует
 * `\`, `` ` ``, `*`, `_`, `[`, `]`, `~` и кодирует HTML-энтити в приватных методах — из-за
 * этого `due_date` превращался в `due\_date`, и строгая сверка v1 уводила такие тела в raw.
 *
 * Снимаем экранирование ТОЧЕЧНО, по правилам, каждое из которых доказуемо безопасно
 * (приёмка — инвариант `parseBody(canonicalizeBody(x).body)` ≡ `parseBody(x)`):
 *  - `_` между словными символами НЕ экранируется: intraword underscore не образует
 *    emphasis по CommonMark/GFM (`due_date` — текст, не курсив);
 *  - одиночный `&` НЕ кодируется, если не начинает сущность (`&amp;`, `&#39;`);
 *  - `<` кодируется ТОЛЬКО перед [a-zA-Z/!?] — потенциальный тег; голое `a < b` остаётся;
 *  - `>` не кодируется вовсе, но экранируется в начале текста — см. escapeBlockStarter;
 *  - всё прочее (`*`, `` ` ``, `[`, `]`, `~`, `\`, `_` на границе слова) экранируется
 *    штатно: снятие сломало бы повторный парс (текст `_курсив_` стал бы курсивом).
 *
 * Сигнатура и ранний выход по `isInsideCode` повторяют штатный метод (сверено с
 * `@tiptap/markdown/dist/index.js:1119`): внутри `code`/`codeBlock` текст обязан оставаться
 * дословным, и потеря этого стража сделала бы код в документе неверным.
 * Наивный путь `Text.extend({ renderMarkdown })` НЕ работает (факт спайка).
 *
 * Метод помечен `private` в `.d.ts` (в рантайме — обычный член прототипа), поэтому TS считает
 * переопределение несовместимым расширением базового класса и ругается на СТРОКУ КЛАССА, а не
 * на строку метода — отсюда директива именно здесь.
 */
// @ts-expect-error TS2415 — encodeTextForMarkdown private только в типах
export class OrbisMarkdownManager extends MarkdownManager {
  protected encodeTextForMarkdown(
    text: string,
    node: TextNodeLike,
    parentNode?: { type?: string } | null,
  ): string {
    // codeTypes собирается из поля `code` расширений — читаем его, а не хардкодим список.
    const { codeTypes } = this as unknown as { codeTypes: Set<string> };
    const isInsideCode =
      (parentNode?.type != null && codeTypes.has(parentNode.type)) ||
      (node.marks ?? []).some((m) => codeTypes.has(typeof m === 'string' ? m : m.type));
    if (isInsideCode) return text;

    return escapeBlockStarter(
      text
        .replace(/(?<=[\p{L}\p{N}])_(?=[\p{L}\p{N}])/gu, UNDERSCORE_SLOT)
        .replace(/([\\`*_[\]~])/g, '\\$1')
        .replaceAll(UNDERSCORE_SLOT, '_')
        // & кодируем только когда он начинает сущность; < — только перед началом тега
        .replace(/&(?=[a-zA-Z]+;|#\d+;|#x[0-9a-fA-F]+;)/g, '&amp;')
        .replace(/<(?=[a-zA-Z/!?])/g, '&lt;'),
    );
  }
}
