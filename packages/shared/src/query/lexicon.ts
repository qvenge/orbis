/**
 * Лексика языка запроса, общая с маркерами тела, — ЛИСТ без единого импорта (спека 1в §5.1).
 *
 * Зачем отдельный лист. Маркер параметра страницы `{{param: …}}` разбирает препроход тела
 * (`doc/page-grammar.ts`), а его значения — это слова языка запроса: варианты — токены дат,
 * подпись — строка в кавычках по правилам текста запроса, имя — то же, что у ссылки `$<имя>`.
 * Препроход листовой по закону (его тянет первый кадр экрана записи), и до разбора запроса
 * (`parse-ast.ts` — реестр, контракты, zod) ему дотянуться нельзя. Вторая копия правил была бы
 * хуже: подпись, которую принял маркер, отверг бы текст запроса, и наоборот. Поэтому правила,
 * нужные обоим, живут здесь одной копией, а `ast.ts`, `parse-ast.ts` и `page-grammar.ts` их
 * импортируют. Листовость сторожат `page-grammar.test.ts` и `placement.test.ts`.
 */

/**
 * Относительное время запроса. Первые четыре — те же, что у дореформенной грамматики
 * (`grammar.ts:18`); четыре новых 1в (спека §3.4) — В КОНЕЦ, чтобы порядок прежних (списки выбора,
 * перечни в схемах тулов) не сдвинулся. Их разворачивает компилятор по «сегодня» и таймзоне
 * владельца, и потому запрос с токеном НЕ статичен (см. `static.ts`). Края каждого токена и
 * подписи — `tokens.ts`. Реэкспорт — `ast.ts` (имя канона), здесь — единственное определение.
 */
export const QUERY_DATE_TOKENS = [
  'today',
  'overdue',
  'next_7d',
  'after_7d',
  'this_week',
  'next_14d',
  'this_month',
  'last_month',
] as const;
export type QueryDateToken = (typeof QUERY_DATE_TOKENS)[number];

/**
 * Имя параметра страницы (спека 1в §5.1): латиница, цифры, `_`. Одна форма у объявления
 * `{{param: <имя>, …}}` и у ссылки `$<имя>` в тексте запроса, и у схемы дерева (`{param}`).
 * Класс RE2, без просмотров: схема дерева едет потребителям через JSON Schema.
 */
export const PARAM_NAME_RE = /^[A-Za-z0-9_]+$/;

/** Маска «символ вне кавычек»; `unclosedAt` — позиция незакрытой кавычки, иначе -1. */
export function quoteMask(text: string): { outside: boolean[]; unclosedAt: number } {
  const outside = new Array<boolean>(text.length).fill(false);
  let quoteOpen = -1;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (quoteOpen !== -1) {
      if (ch === '\\' && (text[i + 1] === '"' || text[i + 1] === '\\')) i++;
      else if (ch === '"') quoteOpen = -1;
    } else if (ch === '"') {
      quoteOpen = i;
    } else {
      outside[i] = true;
    }
  }
  return { outside, unclosedAt: quoteOpen };
}

/** Итог снятия кавычек: значение или отказ с позицией ВНУТРИ `raw` (зовущий прибавит смещение). */
export type UnquoteResult =
  | { ok: true; value: string }
  | { ok: false; message: string; at: number };

/**
 * Снимает обрамляющие кавычки и разэкранирует `\"`, `\\` и `\}`. Значение без кавычек
 * возвращается как есть, но кавычка внутри него — отказ.
 *
 * Третий экран — не грамматика, а РАЗМЕТКА ТЕЛА: печать разводит `}` бэкслешем, чтобы
 * значение с `}}` не закрыло обёртку `{{query:…}}` блока данных (см. `print.ts`), и без
 * симметричного снятия `parse(print(a)) ≡ a` перестало бы держаться на таком значении. Той же
 * обёрткой закрывается маркер параметра — экран нужен и ему.
 *
 * Отказ — результатом, а не исключением: разбор запроса превращает его в `SYNTAX` с позицией,
 * препроход тела — в ошибку блока параметра, и у каждого свой способ сообщить.
 */
export function unquoteValue(raw: string): UnquoteResult {
  if (!raw.startsWith('"')) {
    const q = raw.indexOf('"');
    if (q !== -1) {
      return { ok: false, message: 'кавычки допустимы только вокруг всего значения', at: q };
    }
    return { ok: true, value: raw };
  }
  let out = '';
  let i = 1;
  for (; i < raw.length; i++) {
    const ch = raw[i];
    if (ch === '\\' && (raw[i + 1] === '"' || raw[i + 1] === '\\' || raw[i + 1] === '}')) {
      out += raw[i + 1];
      i++;
      continue;
    }
    if (ch === '"') break;
    out += ch;
  }
  if (i >= raw.length) return { ok: false, message: 'незакрытая кавычка', at: 0 };
  if (i !== raw.length - 1) {
    return { ok: false, message: 'лишние символы после закрывающей кавычки', at: i + 1 };
  }
  return { ok: true, value: out };
}
