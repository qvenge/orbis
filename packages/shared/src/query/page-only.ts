/**
 * Признаки «только для страниц» в дереве запроса (спека 1в §3.8, РП-5): ссылка на параметр `$<имя>`
 * (`{param}` на месте значения-границы) и группировка (`group` у корня — задача 6).
 *
 * Обход — по СЫРОМУ значению, итеративно и без схемы: его зовёт уточнение `queryAstSchema`
 * (`ast.ts`), отказ записи значения с деревом (`executor/props.ts`) и окно материализации, а ещё —
 * web, решающий, какие значения параметров слать. Форму дерева проверяет схема; этот обход только
 * ищет признак и на мусоре отвечает «нет признака», а не падает. Итеративно — по доводу
 * `queryTreeExceedsDepth`: рекурсия на глубоком входе исчерпала бы стек раньше, чем схема успела
 * бы отказать.
 *
 * ССЫЛКА УЗНАЁТСЯ ПО ФОРМЕ, а не по месту: объект с полем `param`-строкой. В каноне так выглядит
 * только ссылка — ключа `param` нет ни у одного узла и ни у одной части проекции, — поэтому обход
 * не перечисляет места границ (`value`, `from`, `to`) и не отстанет, когда ссылка появится в новом.
 * Цена — ноль: ложного срабатывания на законном дереве быть не может, а форму ссылки держит схема.
 * Коротко нарочно: модуль в эагерном замыкании экрана записи (порог веса РП-25).
 *
 * Файл без рантайм-импортов: его импортирует `ast.ts`, и ребро назад замкнуло бы цикл
 * инициализации схем.
 */

/** Имена ссылок дерева — обход в глубину слева направо, с повторами. */
function allParamNames(ast: unknown): string[] {
  const out: string[] = [];
  const stack: unknown[] = [ast];
  while (stack.length > 0) {
    const v = stack.pop();
    if (typeof v !== 'object' || v === null) continue;
    const name = (v as { param?: unknown }).param;
    if (typeof name === 'string' && !Array.isArray(v)) {
      out.push(name);
      continue;
    }
    // Обратным порядком в стек — чтобы снимались слева направо.
    const children = Array.isArray(v) ? v : Object.values(v);
    for (let i = children.length - 1; i >= 0; i--) stack.push(children[i]);
  }
  return out;
}

/**
 * Первый признак «только для страниц» или `null`. Группировка — ключ `group` у корня дерева
 * (задача 6 заводит его форму; признак ищется уже сейчас, чтобы уточнение схемы и отказ разбора не
 * пришлось учить второй раз).
 */
// ОБХОДЧИК-Q: page-only
export function pageOnlyFeatureIn(ast: unknown): 'param' | 'group' | null {
  if (typeof ast !== 'object' || ast === null || Array.isArray(ast)) return null;
  if (allParamNames(ast).length > 0) return 'param';
  return Object.hasOwn(ast, 'group') ? 'group' : null;
}

/**
 * Имена параметров, на которые ссылается дерево, — без повторов, в порядке первого появления. По
 * ним клиент собирает значения элемента пачки (задача 5): лишнее не шлётся, недостающее видно.
 */
export function paramNamesIn(ast: unknown): readonly string[] {
  return [...new Set(allParamNames(ast))];
}
