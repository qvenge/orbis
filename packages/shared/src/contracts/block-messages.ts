// Тексты отказов блока данных (срез 1а, спека §6.5) — ЛИСТОВОЙ модуль без единого импорта.
//
// Почему отдельный файл, а не константы в `blocks.ts` или `doc/placement.ts`. Строки нужны трём
// сторонам: серверу (`entity.blocks`), плашке тела (`bodyIssues`) и клиентскому собирателю пачки
// в начальной загрузке web (`lib/query-blocks/batch.tsx` стоит в `main.tsx`). Импорт из
// `placement.ts` тянул в начальную загрузку препроход тела и разбор дат (≈1 кБ gzip) ради одной
// строки; здесь нет ничего, кроме самих строк. Одна копия текста на все три стороны — иначе плашка
// тела и плашка блока разошлись бы в формулировке одного и того же отказа.

