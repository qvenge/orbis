// packages/shared/src/contracts/errors.ts
// Структурный отказ на проводе (спека скорости §8.2, РП-5 плана А): поле `data.orbis` ответа об ошибке tRPC. Сервер
// кладёт его только для отказов из ЗАКРЫТОГО списка кодов и только с перечисленными полями (`orbisErrorData`,
// `apps/server/src/errors.ts`), клиент читает его `orbisErrorOf` (`apps/web/src/lib/orbis-error.ts`). Тексты записей
// сюда не попадают никогда — только id, ревизии, актор, время, место продолжения, расхождения предусловия.
// Только типы: web тянет отсюда форму, а не код.

/**
 * Код отказа исполнителя и его безопасные поля. `code` — строка, а не союз кодов сервера: список кодов, которым
 * положены поля, растёт по задачам плана (замок заголовка, правило отмены), и клиенту важен код, а не полнота перечня.
 */
export interface OrbisErrorData {
  code: string;
  details?: Record<string, unknown>;
}
